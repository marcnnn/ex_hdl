defmodule ExHdl.Backends.SystemVerilog.Protocol do
  @moduledoc """
  Emits synthesizable SystemVerilog-2012 for a `ExHdl.Protocol.Spec`:

    * `<name>_parser` - AXI4-Stream slave that strips and validates the
      header chain, exposes the fields as `meta_*` and forwards the payload,
      realigned to lane 0, with full backpressure.
    * `<name>_emitter` - prepends a header built from `meta_*` to a payload
      stream.
    * `<name>_loopback` - parser feeding emitter, used for co-simulation.

  ## Parser

  Header bytes are captured into a byte register (`hdr_q`, as many bytes as
  the longest header) at their packet offset; the bytes of the beat being
  accepted are visible combinationally (`hdr_n`). Every header layout of
  `ExHdl.Protocol.Layout` is matched in parallel: a layout is complete in the
  beat that holds its last header byte, if its selector and header-length
  conditions hold. That beat decides the packet: asserts, runtime matches,
  header checksums (accumulated per beat for every possible start of the
  layer), total-length consistency and `tkeep` (all ones except on the
  `tlast` beat, where it must be contiguous from lane 0). A failing packet,
  or one that ends inside its header or has no payload, is dropped up to
  `tlast` and counted in `dropped_packets`.

  The payload is shifted so its first byte is in lane 0 (one register of
  the previous beat, no bubble); when its last beat does not fit, one extra
  flush beat follows, during which the parser already accepts the next
  packet's first beat. With total-length fields the payload ends where the
  innermost one says (trailing bytes such as Ethernet padding are dropped)
  and `meta_payload_bytes` gives its length.

  Some checks are only known at the end: a packet shorter than its length
  field, and segment checksums (UDP), which the parser accumulates over the
  payload as it passes. Instead of store-and-forward these set
  `m_axis_tuser` on the last payload beat (port present only if the spec
  has such fields); the consumer discards the packet, as with a MAC's bad
  FCS flag.

  `meta_*` are registered when the header is accepted and stay valid until
  the last payload beat has been handed over (`meta_valid`). Ports:
  `meta_<field>` for a single header block, `meta_<layer>_<field>` for
  chains (`meta_<layer><i>_<field>` for repeated layers, absent layers read
  0), `meta_<layer>_count` for layers that are not on every packet,
  `meta_<layer>_<field>` of `:bytes` fields with byte `i` at `[8*i +: 8]`.
  A `match: n` field has the inputs `match_<layer>_<field>` (`n` packed
  entries) and `match_<layer>_<field>_en`, and the output
  `meta_<layer>_<field>_hit` (which entries matched).

  ## Emitter

  `meta_*` and `payload_bytes` are sampled while the first payload beat is
  pending (`s_axis_tvalid` high), so they must be stable from then until
  that beat is accepted. Asserted fields are constants; total lengths come
  from `payload_bytes`, header checksums are computed. A segment checksum
  over the payload would need store-and-forward, so it is an input like any
  field: compute it upstream or send 0 (UDP: no checksum). The selector and
  header-length inputs choose the layout; a combination without a layout
  drops the payload packet (`dropped_packets`, present when there are
  several layouts). The payload is shifted to start right after the header.
  `s_axis_tuser` of the last payload beat is passed to `m_axis_tuser` if
  the spec has `tuser`.

  `tvalid` never depends on `tready`. Both modules run one beat per cycle.
  """

  import Bitwise
  alias ExHdl.Protocol.{Field, Layer, Layout, Spec}

  @header "// Generated by ExHdl from defpacket. Do not edit.\n"

  @doc """
  Returns `%{filename => source}` for all modules of the spec. `match:` (a
  map from `{layer, field}` or field name to a list of values) sets the
  constant tables the loopback ties to the parser's match inputs.
  """
  def generate(%Spec{} = spec, opts \\ []) do
    m = model(spec)

    %{
      "#{spec.name}_parser.sv" => parser(m),
      "#{spec.name}_emitter.sv" => emitter(m),
      "#{spec.name}_loopback.sv" => loopback(m, opts)
    }
  end

  @doc """
  Non-AXI ports of `<name>_parser`, `_emitter` or `_loopback` as
  `{name, :input | :output, bits, signed}`. AXI4-Stream bundles are
  `s_axis`/`m_axis` with tdata, tkeep, tlast (and a 1-bit tuser if
  `Spec.tuser?/1`).
  """
  def ports(%Spec{} = spec, which) when which in [:parser, :emitter, :loopback] do
    m = model(spec)

    case which do
      :parser -> parser_ports(m)
      :emitter -> emitter_ports(m)
      :loopback -> [{"dropped_packets", :output, 32, false}]
    end
    |> Enum.map(fn {name, dir, bits, signed} -> {String.to_atom(name), dir, bits, signed} end)
  end

  # -- model -------------------------------------------------------------------

  defp model(%Spec{} = spec) do
    k = div(spec.bus_width, 8)
    paths = Layout.paths(spec)
    maxh = Layout.max_header_bytes(paths)
    nb = div(maxh + k - 1, k)
    order = spec.layers |> Enum.with_index() |> Map.new(fn {l, i} -> {l.name, i} end)
    insts = paths |> Layout.instances() |> Enum.sort_by(fn {l, i} -> {order[l], i} end)

    %{
      spec: spec,
      k: k,
      paths: paths,
      np: length(paths),
      maxh: maxh,
      nb: nb,
      bw: clog2(nb + 1),
      insts: insts,
      tuser: Spec.tuser?(spec),
      lengths: Spec.length_fields?(spec)
    }
  end

  defp layer_of(m, {lname, _}), do: Spec.layer(m.spec, lname)

  defp iname(%{spec: %Spec{flat: true}}, _), do: "h"

  defp iname(m, {lname, i} = inst) do
    if layer_of(m, inst).max == 1, do: "#{lname}", else: "#{lname}#{i}"
  end

  defp prefix(%{spec: %Spec{flat: true}}, _), do: "meta_"
  defp prefix(m, inst), do: "meta_#{iname(m, inst)}_"

  defp steps_of(path, inst), do: Enum.find(path.steps, &(&1.inst == inst))

  defp tail_bytes(m, inst) do
    l = layer_of(m, inst)
    {_, max} = Layer.size_range(l)
    max - l.fixed_bytes
  end

  defp field_width(m, inst, %Field{kind: :bytes}), do: 8 * tail_bytes(m, inst)
  defp field_width(_m, _inst, f), do: f.bits

  defp sv_type(1, false), do: "logic"
  defp sv_type(bits, true), do: "logic signed [#{bits - 1}:0]"
  defp sv_type(bits, false), do: "logic [#{bits - 1}:0]"

  # Layers that are absent on some packets get a count output.
  defp counted_layers(%{spec: %Spec{flat: true}}), do: []

  defp counted_layers(m) do
    for l <- m.spec.layers,
        Enum.any?(m.paths, fn p -> Enum.count(p.steps, &(elem(&1.inst, 0) == l.name)) != l.max end),
        do: l
  end

  defp match_fields(m) do
    for inst <- m.insts, f <- layer_of(m, inst).fields, f.match != nil, do: {inst, f}
  end

  defp seg_fields(m) do
    for inst <- m.insts, f <- layer_of(m, inst).fields, f.checksum == :segment, do: {inst, f}
  end

  # -- ports -------------------------------------------------------------------

  defp parser_ports(m) do
    meta =
      for inst <- m.insts, f <- layer_of(m, inst).fields do
        {"#{prefix(m, inst)}#{f.name}", :output, field_width(m, inst, f), f.signed}
      end

    counts =
      for l <- counted_layers(m),
          do: {"meta_#{l.name}_count", :output, clog2(l.max + 1), false}

    hits =
      for {inst, f} <- match_fields(m),
          do: {"#{prefix(m, inst)}#{f.name}_hit", :output, f.match, false}

    tables =
      for {inst, f} <- match_fields(m) do
        base = "match_#{iname(m, inst)}_#{f.name}"
        [{base, :input, f.match * f.bits, false}, {"#{base}_en", :input, f.match, false}]
      end

    plen = if m.lengths, do: [{"meta_payload_bytes", :output, 16, false}], else: []

    List.flatten(tables) ++
      [{"meta_valid", :output, 1, false}] ++
      meta ++ counts ++ hits ++ plen ++ [{"dropped_packets", :output, 32, false}]
  end

  defp emitter_inputs(m) do
    for inst <- m.insts, f <- layer_of(m, inst).fields, emitter_input?(f) do
      {"#{prefix(m, inst)}#{f.name}", :input, field_width(m, inst, f), f.signed}
    end
  end

  defp emitter_input?(f), do: f.assert == nil and f.length == nil and f.checksum != :header

  defp emitter_drops?(m), do: m.np > 1 or hd(m.paths).conds != []

  defp emitter_ports(m) do
    plen = if m.lengths, do: [{"payload_bytes", :input, 16, false}], else: []
    drops = if emitter_drops?(m), do: [{"dropped_packets", :output, 32, false}], else: []
    emitter_inputs(m) ++ plen ++ drops
  end

  defp port_decls(ports) do
    Enum.map(ports, fn {name, dir, bits, signed} ->
      d = if dir == :input, do: "input ", else: "output"
      "  #{d} #{sv_type(bits, signed)} #{name},\n"
    end)
  end

  defp axis_ports(m, tuser_in, tuser_out, more? \\ true) do
    w = m.spec.bus_width
    k = m.k

    """
      input  logic [#{w - 1}:0] s_axis_tdata,
      input  logic [#{k - 1}:0] s_axis_tkeep,
      input  logic        s_axis_tlast,
    #{if tuser_in, do: "  input  logic        s_axis_tuser,\n"}  input  logic        s_axis_tvalid,
      output logic        s_axis_tready,

      output logic [#{w - 1}:0] m_axis_tdata,
      output logic [#{k - 1}:0] m_axis_tkeep,
      output logic        m_axis_tlast,
    #{if tuser_out, do: "  output logic        m_axis_tuser,\n"}  output logic        m_axis_tvalid,
      input  logic        m_axis_tready#{if more?, do: ","}
    """
  end

  # -- field extraction ----------------------------------------------------------

  # Expression for field `f` of a layer starting at byte `c` of byte vector `src`
  # (byte j at [8j +: 8]).
  defp extract(m, src, c, %Field{kind: :bytes} = f, inst) do
    l = layer_of(m, inst)
    _ = f

    bytes =
      for i <- (tail_bytes(m, inst) - 1)..0//-1 do
        j = c + l.fixed_bytes + i
        if j < m.maxh, do: "#{src}[#{8 * j + 7}:#{8 * j}]", else: "8'h0"
      end

    concat(bytes)
  end

  defp extract(%{spec: %Spec{byte_order: :little}}, src, c, f, _inst) do
    lo = 8 * c + f.offset
    "#{src}[#{lo + f.bits - 1}:#{lo}]"
  end

  defp extract(_m, src, c, f, _inst) do
    a = 8 * c + f.offset
    n = f.bits

    parts =
      for b <- div(a, 8)..div(a + n - 1, 8) do
        first = max(a, 8 * b) - 8 * b
        last = min(a + n, 8 * b + 8) - 1 - 8 * b
        hi = 8 * b + 7 - first
        lo = 8 * b + 7 - last
        if hi == lo, do: "#{src}[#{hi}]", else: "#{src}[#{hi}:#{lo}]"
      end

    concat(parts)
  end

  defp concat([one]), do: one
  defp concat(parts), do: "{#{Enum.join(parts, ", ")}}"

  defp fwire(m, inst, c, fname), do: "f_#{iname(m, inst)}_#{c}_#{fname}"

  defp placements(m) do
    m.paths
    |> Enum.flat_map(fn p -> Enum.map(p.steps, &{&1.inst, &1.start}) end)
    |> Enum.uniq()
  end

  # Condition expression; `val.(inst, c, field)` gives the field value expression.
  defp cond_expr(m, {inst, c, fname, cond}, val) do
    f = Layer.field(layer_of(m, inst), fname)
    v = val.(inst, c, fname)

    case cond do
      {:eq, x} -> "(#{v} == #{lit(x, f.bits)})"
      {:in, xs} -> "(#{Enum.map_join(xs, " || ", &"#{v} == #{lit(&1, f.bits)}")})"
      {:not_in, xs} -> "!(#{Enum.map_join(xs, " || ", &"#{v} == #{lit(&1, f.bits)}")})"
    end
  end

  # AND-OR mux over the path vector `vec`: `exprs` is one expression per path
  # (nil where the path does not contribute).
  defp path_mux(vec, width, exprs) do
    terms =
      exprs
      |> Enum.with_index()
      |> Enum.reject(fn {e, _} -> e == nil end)
      |> Enum.group_by(fn {e, _} -> e end, fn {_, i} -> i end)
      |> Enum.sort_by(fn {_, is} -> hd(is) end)

    case terms do
      [] ->
        "#{width}'(0)"

      [{e, is}] when length(is) == length(exprs) ->
        e

      _ ->
        terms
        |> Enum.map(fn {e, is} ->
          sel = Enum.map_join(is, " | ", &"#{vec}[#{&1}]")
          if width == 1, do: "((#{sel}) & #{e})", else: "({#{width}{#{sel}}} & #{e})"
        end)
        |> Enum.join("\n      | ")
    end
  end

  # -- parser ------------------------------------------------------------------

  defp parser(m) do
    spec = m.spec
    w = spec.bus_width
    k = m.k
    bw = m.bw
    maxh = m.maxh
    np = m.np
    ports = parser_ports(m)
    plc = placements(m)

    beat = fn q -> "(beat == #{bw}'d#{q})" end

    hdr_n =
      for j <- 0..(maxh - 1) do
        "  assign hdr_n[#{8 * j + 7}:#{8 * j}] = #{beat.(div(j, k))} ? s_axis_tdata[#{8 * rem(j, k) + 7}:#{8 * rem(j, k)}] : hdr_q[#{8 * j + 7}:#{8 * j}];\n"
      end

    fwires =
      for {inst, c} <- plc, f <- layer_of(m, inst).fields do
        width = field_width(m, inst, f)

        "  #{sv_type(width, f.signed)} #{fwire(m, inst, c, f.name)};\n" <>
          "  assign #{fwire(m, inst, c, f.name)} = #{extract(m, "hdr_n", c, f, inst)};\n"
      end

    val = fn inst, c, fname -> fwire(m, inst, c, fname) end

    # header checksum accumulators per placement
    csum_plc =
      for {inst, c} <- plc,
          f = Enum.find(layer_of(m, inst).fields, &(&1.checksum == :header)),
          f != nil,
          do: {inst, c}

    offsets =
      if csum_plc == [] do
        ""
      else
        lane_bits = clog2(k)

        for l <- 0..(k - 1) do
          off = if k == 1, do: "16'(beat)", else: "16'({beat, #{lane_bits}'d#{l}})"
          "  logic [15:0] off_#{l};\n  assign off_#{l} = #{off};\n"
        end
        |> Enum.join()
      end

    csums = Enum.map(csum_plc, fn {inst, c} -> header_csum(m, inst, c) end)

    csum_ok = fn inst, c -> "hck_#{iname(m, inst)}_#{c}_ok" end

    # field values of the decided layout (valid while done is one-hot)
    vwire = fn inst, fname -> "v_#{iname(m, inst)}_#{fname}" end

    selected =
      for inst <- m.insts, f <- layer_of(m, inst).fields do
        width = field_width(m, inst, f)

        exprs =
          Enum.map(m.paths, fn p ->
            case steps_of(p, inst) do
              nil -> nil
              st -> fwire(m, inst, st.start, f.name)
            end
          end)

        "  #{sv_type(width, f.signed)} #{vwire.(inst, f.name)};\n" <>
          "  assign #{vwire.(inst, f.name)} = #{path_mux("done", width, exprs)};\n"
      end

    hit_wires =
      for {inst, f} <- match_fields(m) do
        base = "match_#{iname(m, inst)}_#{f.name}"
        name = "hit_#{iname(m, inst)}_#{f.name}"

        bits =
          for e <- (f.match - 1)..0//-1 do
            "(#{base}_en[#{e}] && #{base}[#{e * f.bits + f.bits - 1}:#{e * f.bits}] == #{vwire.(inst, f.name)})"
          end

        "  logic [#{f.match - 1}:0] #{name};\n  assign #{name} = {#{Enum.join(bits, ", ")}};\n"
      end

    length_wires = length_wires(m, vwire)

    # per path decision
    done_logic =
      for p <- m.paths do
        q = div(p.payload - 1, k)
        lane = rem(p.payload - 1, k)
        conds = Enum.map(p.conds, &cond_expr(m, &1, val))
        done = Enum.join(["#{beat.(q)}", "s_axis_tkeep[#{lane}]" | conds], "\n      && ")

        """
          // path #{p.id}: #{describe(m, p)}
          assign done[#{p.id}] = #{done};
        """
      end

    ok_logic =
      for p <- m.paths do
        checks =
          for step <- p.steps, f <- step.layer.fields, reduce: [] do
            acc ->
              wv = vwire.(step.inst, f.name)

              acc ++
                cond do
                  f.assert != nil -> ["(#{wv} == #{lit(f.assert, f.bits)})"]
                  f.checksum == :header -> [csum_ok.(step.inst, step.start)]
                  f.match != nil -> ["(|hit_#{iname(m, step.inst)}_#{f.name})"]
                  true -> []
                end
          end

        checks = checks ++ length_checks(m, p)
        ok = if checks == [], do: "1'b1", else: Enum.join(checks, "\n      && ")
        "  assign ok[#{p.id}] = #{ok};\n"
      end

    path_logic = [done_logic, "\n", selected, hit_wires, length_wires, "\n", ok_logic]

    s_of = fn p -> rem(p.payload, k) end

    pib =
      path_mux(
        "done",
        1,
        Enum.map(m.paths, fn p ->
          if s_of.(p) == 0, do: "1'b0", else: "s_axis_tkeep[#{s_of.(p)}]"
        end)
      )

    sh_new =
      path_mux("done", 8, Enum.map(m.paths, &"8'd#{if s_of.(&1) == 0, do: k, else: s_of.(&1)}"))

    s_new = path_mux("done", 8, Enum.map(m.paths, &"8'd#{s_of.(&1)}"))

    {limit_new, limit_en_new} =
      if m.lengths do
        {path_mux("done", 16, Enum.map(m.paths, &limit_expr(m, &1))),
         path_mux(
           "done",
           1,
           Enum.map(m.paths, &if(innermost_length(&1), do: "1'b1", else: "1'b0"))
         )}
      else
        {nil, nil}
      end

    meta_latch =
      for inst <- m.insts,
          f <- layer_of(m, inst).fields,
          do: "        #{prefix(m, inst)}#{f.name} <= #{vwire.(inst, f.name)};\n"

    count_latch =
      for l <- counted_layers(m) do
        cw = clog2(l.max + 1)

        exprs =
          Enum.map(m.paths, fn p ->
            "#{cw}'d#{Enum.count(p.steps, &(elem(&1.inst, 0) == l.name))}"
          end)

        "        meta_#{l.name}_count <= #{path_mux("done", cw, exprs)};\n"
      end

    hit_latch =
      for {inst, f} <- match_fields(m),
          do: "        #{prefix(m, inst)}#{f.name}_hit <= hit_#{iname(m, inst)}_#{f.name};\n"

    segs = seg_fields(m)

    seg_en_latch =
      for {{inst, _f}, i} <- Enum.with_index(segs) do
        exprs = Enum.map(m.paths, fn p -> if steps_of(p, inst), do: "1'b1", else: nil end)
        "        seg_en_q[#{i}] <= #{path_mux("done", 1, exprs)};\n"
      end

    plen_latch = if m.lengths, do: "        meta_payload_bytes <= limit_new;\n", else: ""

    tuser_logic = if m.tuser, do: parser_tuser(m, segs), else: ""

    lint_on = "  /* verilator lint_on UNUSEDSIGNAL */\n"

    """
    #{@header}
    module #{spec.name}_parser (
      input  logic        clk,
      input  logic        rst_n,

      // AXI4-Stream slave: complete packets
      // AXI4-Stream master: payload only, first byte in lane 0
    #{axis_ports(m, false, m.tuser)}
    #{port_decls(ports) |> Enum.join() |> String.trim_trailing(",\n")}
    );
      /* verilator lint_off UNUSEDSIGNAL */
      typedef enum logic [1:0] {S_HEADER = 2'd0, S_PAYLOAD = 2'd1, S_FLUSH = 2'd2, S_DROP = 2'd3} state_t;
      state_t state;

      // header capture: byte j of the packet at [8j +: 8]
      logic [#{bw - 1}:0] beat;              // beat index inside the header, saturating
      logic [#{8 * maxh - 1}:0] hdr_q, hdr_n;
      logic [#{w - 1}:0] prev;               // previous accepted beat
      logic        keep_bad, keep_bad_q;
      logic [7:0]  keep_cnt;
      logic        hdr_phase, hdr_beat;
      logic [#{np - 1}:0] done, ok;
      logic        decide, accept, pay_in_beat;
      logic [7:0]  sh_q, flush_n_q, sh_new, s_new;

      assign hdr_phase = (state == S_HEADER) || (state == S_FLUSH);
      assign hdr_beat  = s_axis_tvalid && s_axis_tready && hdr_phase;
      assign keep_cnt  = #{keep_count(k)};
      assign keep_bad  = s_axis_tlast ? #{keep_contig_bad(k)} : (s_axis_tkeep != #{k}'h#{hex(bsl(1, k) - 1)});

    #{hdr_n}
    #{fwires}
    #{offsets}#{csums}
    #{path_logic}
      assign decide      = |done;
      assign pay_in_beat = #{pib};
      assign accept      = |(done & ok) && !keep_bad && !keep_bad_q && (!s_axis_tlast || pay_in_beat);
      assign sh_new      = #{sh_new};
      assign s_new       = #{s_new};
    #{limit_wires(m, limit_new, limit_en_new)}
      // payload realignment: output = ({cur, prev} >> 8*sh)
      logic [#{w - 1}:0] cur;
      logic [#{2 * w - 1}:0] cat;
      logic [#{w - 1}:0] shifted;
      logic [7:0]  n_avail, n_out;
      logic        last_in, out_last, go_flush, trim;

      assign cur = (state == S_FLUSH) ? '0 : s_axis_tdata;
      assign cat = {cur, prev};
      always_comb begin
        case (sh_q)
    #{for j <- 1..k, do: "      8'd#{j}: shifted = cat[#{8 * j + w - 1}:#{8 * j}];\n"}      default: shifted = cat[#{2 * w - 1}:#{w}];
        endcase
      end

      always_comb begin
        last_in = (state == S_FLUSH) || s_axis_tlast;
        n_avail = (state == S_FLUSH) ? flush_n_q
                : 8'd#{k} - sh_q + (s_axis_tlast ? keep_cnt : 8'd#{k});
        n_out = (n_avail > 8'd#{k}) ? 8'd#{k} : n_avail;
        out_last = 1'b0;
        go_flush = 1'b0;
        trim = 1'b0;
    #{limit_comb(m)}    if (!trim) begin
          if (last_in && n_avail <= 8'd#{k}) out_last = 1'b1;
          else if (last_in) go_flush = 1'b1;
        end
      end

      assign m_axis_tdata  = shifted;
    #{for l <- 0..(k - 1), do: "  assign m_axis_tkeep[#{l}] = (n_out > 8'd#{l});\n"}  assign m_axis_tlast  = out_last;
      assign m_axis_tvalid = ((state == S_PAYLOAD) && s_axis_tvalid) || (state == S_FLUSH);
      assign s_axis_tready = (state == S_PAYLOAD || state == S_FLUSH) ? m_axis_tready : 1'b1;
    #{tuser_logic}
      always_ff @(posedge clk) begin
        if (!rst_n) begin
          state           <= S_HEADER;
          beat            <= '0;
          keep_bad_q      <= 1'b0;
          meta_valid      <= 1'b0;
          dropped_packets <= '0;
        end else begin
          // output side
          if (state == S_PAYLOAD && s_axis_tvalid && m_axis_tready) begin
            if (out_last) begin
              state      <= s_axis_tlast ? S_HEADER : S_DROP;
              meta_valid <= 1'b0;
            end else if (go_flush) begin
              state <= S_FLUSH;
            end
          end
          if (state == S_FLUSH && m_axis_tready) begin
            state      <= S_HEADER;
            meta_valid <= 1'b0;
          end
          if (state == S_DROP && s_axis_tvalid && s_axis_tlast) state <= S_HEADER;

          // header side (also during the flush beat of the previous packet)
          if (hdr_beat) begin
            if (decide || s_axis_tlast) begin
              beat       <= '0;
              keep_bad_q <= 1'b0;
            end else begin
              if (beat != #{bw}'d#{m.nb}) beat <= beat + #{bw}'d1;
              keep_bad_q <= keep_bad_q | keep_bad;
            end

            if (decide && accept) begin
              state      <= s_axis_tlast ? S_FLUSH : S_PAYLOAD;
              meta_valid <= 1'b1;
            end else if (decide || s_axis_tlast) begin
              // bad header, runt, or header without payload
              dropped_packets <= dropped_packets + 32'd1;
              state <= s_axis_tlast ? S_HEADER : S_DROP;
            end else begin
              state <= S_HEADER;
            end
          end
        end
      end

      // datapath registers (no reset needed, qualified by state)
      always_ff @(posedge clk) begin
        if (s_axis_tvalid && s_axis_tready) prev <= s_axis_tdata;
        if (hdr_beat) hdr_q <= hdr_n;
    #{csum_regs(csum_plc, m)}    if (state == S_PAYLOAD && s_axis_tvalid && m_axis_tready && go_flush)
          flush_n_q <= n_avail - 8'd#{k};
    #{out_regs(m)}    if (hdr_beat && decide && accept) begin
          sh_q      <= sh_new;
          flush_n_q <= keep_cnt - s_new;
    #{meta_latch}#{count_latch}#{hit_latch}#{seg_en_latch}#{plen_latch}#{limit_latch(m)}    end
      end
    #{lint_on}endmodule
    """
    |> tidy()
  end

  defp keep_count(1), do: "8'(s_axis_tkeep)"
  defp keep_count(k), do: Enum.map_join(0..(k - 1), " + ", &"8'(s_axis_tkeep[#{&1}])")

  defp keep_contig_bad(1), do: "!s_axis_tkeep[0]"

  defp keep_contig_bad(k),
    do: "(!s_axis_tkeep[0] || ((s_axis_tkeep & (s_axis_tkeep + #{k}'d1)) != #{k}'d0))"

  defp describe(m, p) do
    steps = Enum.map_join(p.steps, " -> ", &"#{iname(m, &1.inst)}@#{&1.start}+#{&1.hlen}")
    "#{steps} -> payload@#{p.payload}"
  end

  defp length_steps(p) do
    for st <- p.steps, f <- st.layer.fields, f.length == :total, do: {st, f}
  end

  defp innermost_length(p), do: List.last(length_steps(p))

  defp limit_expr(m, p) do
    case innermost_length(p) do
      nil -> "16'd0"
      {st, _f} -> "16'(e_#{iname(m, st.inst)} - 17'(pay_sel))"
    end
  end

  # End offsets (start + total length) of the length layers in the decided
  # layout, and its payload offset.
  defp length_wires(%{lengths: false}, _vwire), do: ""

  defp length_wires(m, vwire) do
    pay = path_mux("done", 16, Enum.map(m.paths, &"16'd#{&1.payload}"))

    ends =
      for inst <- m.insts,
          f = Enum.find(layer_of(m, inst).fields, &(&1.length == :total)),
          f != nil do
        n = iname(m, inst)

        starts =
          Enum.map(m.paths, fn p ->
            case steps_of(p, inst) do
              nil -> nil
              st -> "16'd#{st.start}"
            end
          end)

        "  logic [15:0] st_#{n};\n  logic [16:0] e_#{n};\n" <>
          "  assign st_#{n} = #{path_mux("done", 16, starts)};\n" <>
          "  assign e_#{n} = 17'(st_#{n}) + 17'(#{vwire.(inst, f.name)});\n"
      end

    ["  logic [15:0] pay_sel;\n  assign pay_sel = #{pay};\n" | ends]
  end

  # Innermost total length covers at least one payload byte; each length fits
  # inside the enclosing one.
  defp length_checks(m, p) do
    ls = length_steps(p)
    e = fn {st, _} -> "e_#{iname(m, st.inst)}" end

    inner =
      case List.last(ls) do
        nil -> []
        last -> ["(#{e.(last)} > 17'(pay_sel))"]
      end

    nested =
      ls
      |> Enum.chunk_every(2, 1, :discard)
      |> Enum.map(fn [o, i] -> "(#{e.(o)} >= #{e.(i)})" end)

    inner ++ nested
  end

  defp limit_wires(%{lengths: false}, _, _), do: ""

  defp limit_wires(_m, limit_new, limit_en_new) do
    """
      // payload length from the innermost total-length field
      logic [15:0] limit_new, limit_q, out_cnt, rem_bytes;
      logic        limit_en_new, limit_en_q;
      assign limit_new    = #{limit_new};
      assign limit_en_new = #{limit_en_new};
      assign rem_bytes    = limit_q - out_cnt;
    """
  end

  defp limit_comb(%{lengths: false}), do: ""

  defp limit_comb(_m) do
    """
        if (limit_en_q && rem_bytes <= 16'(n_out)) begin
          n_out    = rem_bytes[7:0];
          out_last = 1'b1;
          trim     = 1'b1;
        end
    """
  end

  defp limit_latch(%{lengths: false}), do: ""

  defp limit_latch(_m) do
    "      limit_q    <= limit_new;\n      limit_en_q <= limit_en_new;\n"
  end

  defp out_regs(m) do
    if m.lengths or seg_fields(m) != [] do
      sum = if seg_fields(m) != [], do: "      acc_out <= acc_out_n;\n", else: ""
      cnt = if m.lengths or seg_fields(m) != [], do: "      out_cnt <= out_cnt + 16'(n_out);\n"

      """
          if (m_axis_tvalid && m_axis_tready) begin
      #{cnt}#{sum}    end
          if (hdr_beat && decide && accept) begin
            out_cnt <= '0;
      #{if sum != "", do: "      acc_out <= '0;\n"}    end
      """
    else
      ""
    end
  end

  # Ones' complement accumulator over the bytes of a layer placed at byte c.
  defp header_csum(m, inst, c) do
    l = layer_of(m, inst)
    k = m.k
    n = "hck_#{iname(m, inst)}_#{c}"
    {minlen, _} = Layer.size_range(l)

    hl =
      case l.hlen_field do
        nil ->
          "16'd#{l.fixed_bytes}"

        hf ->
          unit = Layer.field(l, hf).header_length
          "(16'(#{fwire(m, inst, c, hf)}) * 16'd#{unit})"
      end

    lanes =
      for lane <- 0..(k - 1) do
        byte = "s_axis_tdata[#{8 * lane + 7}:#{8 * lane}]"

        incl =
          "(off_#{lane} >= 16'd#{c}) && ((off_#{lane} < 16'd#{c + minlen}) || (off_#{lane} < 16'd#{c} + #{n}_len))"

        weighted =
          "((off_#{lane}[0] == 1'b#{band(c, 1)}) ? {8'h0, #{byte}, 8'h0} : {16'h0, #{byte}})"

        "(#{incl} ? #{weighted} : 24'h0)"
      end

    """
      // header checksum of #{iname(m, inst)} at byte #{c}
      logic [15:0] #{n}_len;
      logic [23:0] #{n}_acc, #{n}_next;
      logic [16:0] #{n}_f1;
      logic [15:0] #{n}_f2;
      logic        #{n}_ok;
      assign #{n}_len  = #{hl};
      assign #{n}_next = ((beat == '0) ? 24'h0 : #{n}_acc)
          + #{Enum.join(lanes, "\n          + ")};
      assign #{n}_f1 = 17'(#{n}_next[15:0]) + 17'(#{n}_next[23:16]);
      assign #{n}_f2 = #{n}_f1[15:0] + 16'(#{n}_f1[16]);
      assign #{n}_ok = (#{n}_f2 == 16'hFFFF);
    """
  end

  defp csum_regs(plc, m) do
    for {inst, c} <- plc do
      n = "hck_#{iname(m, inst)}_#{c}"
      "    if (hdr_beat) #{n}_acc <= #{n}_next;\n"
    end
  end

  # m_axis_tuser: truncated packet or failed segment checksum, on the last beat.
  defp parser_tuser(m, segs) do
    k = m.k

    trunc =
      if m.lengths,
        do: "limit_en_q && !trim && (out_cnt + 16'(n_out) < limit_q)",
        else: "1'b0"

    seg =
      if segs == [] do
        "  assign seg_bad = 1'b0;\n"
      else
        lanes =
          for l <- 0..(k - 1) do
            byte = "shifted[#{8 * l + 7}:#{8 * l}]"
            par = if rem(l, 2) == 0, do: "out_cnt[0]", else: "!out_cnt[0]"

            "((n_out > 8'd#{l}) ? (#{par} ? {24'h0, #{byte}} : {16'h0, #{byte}, 8'h0}) : 32'h0)"
          end

        checks =
          for {{inst, f}, i} <- Enum.with_index(segs) do
            l = layer_of(m, inst)
            n = "seg#{i}"
            hbytes = l.fixed_bytes
            pad = if rem(hbytes, 2) == 1, do: ", 8'h0", else: ""

            hdr =
              "{" <>
                Enum.map_join(Enum.reject(l.fields, &(&1.kind == :bytes)), ", ", fn f2 ->
                  "#{prefix(m, inst)}#{f2.name}"
                end) <> pad <> "}"

            hwords = div(hbytes + 1, 2)

            words =
              for j <- 0..(hwords - 1),
                  do: "24'(#{n}_hdr[#{16 * hwords - 1 - 16 * j}:#{16 * hwords - 16 - 16 * j}])"

            pseudo =
              for ref <- f.pseudo do
                {lname, fname} = if is_atom(ref), do: {elem(inst, 0), ref}, else: ref
                pinst = if lname == elem(inst, 0), do: inst, else: {lname, 0}
                pf = Layer.field(Spec.layer(m.spec, lname), fname)
                wbits = div(pf.bits + 15, 16) * 16
                name = "#{prefix(m, pinst)}#{fname}"

                for j <- 0..(div(wbits, 16) - 1) do
                  hi = wbits - 1 - 16 * j
                  lo = hi - 15

                  cond do
                    lo >= pf.bits -> nil
                    pf.bits == 1 -> "24'(#{name})"
                    hi < pf.bits -> "24'(#{name}[#{hi}:#{lo}])"
                    true -> "24'(#{name}[#{pf.bits - 1}:#{lo}])"
                  end
                end
                |> Enum.reject(&is_nil/1)
              end
              |> List.flatten()

            swap = rem(hbytes, 2) == 1
            pay = if swap, do: "{pay_f2[7:0], pay_f2[15:8]}", else: "pay_f2"
            opt = if f.optional, do: " || (#{prefix(m, inst)}#{f.name} == 16'h0)", else: ""

            """
              logic [#{16 * hwords - 1}:0] #{n}_hdr;
              logic [23:0] #{n}_sum;
              logic [16:0] #{n}_f1;
              logic [15:0] #{n}_f2;
              assign #{n}_hdr = #{hdr};
              assign #{n}_sum = #{Enum.join(words ++ pseudo, " + ")} + 24'(#{pay});
              assign #{n}_f1  = 17'(#{n}_sum[15:0]) + 17'(#{n}_sum[23:16]);
              assign #{n}_f2  = #{n}_f1[15:0] + 16'(#{n}_f1[16]);
              assign seg_ok[#{i}] = (#{n}_f2 == 16'hFFFF)#{opt};
            """
          end

        """
          // segment checksums: payload bytes summed as they leave (even index = high byte)
          logic [31:0] acc_out, acc_out_n;
          logic [16:0] pay_f1;
          logic [15:0] pay_f2;
          logic [#{length(segs) - 1}:0] seg_en_q, seg_ok;
          assign acc_out_n = acc_out
              + #{Enum.join(lanes, "\n      + ")};
          assign pay_f1 = 17'(acc_out_n[15:0]) + 17'(acc_out_n[31:16]);
          assign pay_f2 = pay_f1[15:0] + 16'(pay_f1[16]);
        #{checks}
          assign seg_bad = |(seg_en_q & ~seg_ok);
        """
      end

    cnt_decl =
      if m.lengths, do: "", else: "  logic [15:0] out_cnt;\n"

    """
    #{cnt_decl}  logic        seg_bad;
    #{seg}  assign m_axis_tuser = out_last && ((#{trunc}) || seg_bad);
    """
  end

  # -- emitter -----------------------------------------------------------------

  defp emitter(m) do
    spec = m.spec
    w = spec.bus_width
    k = m.k
    np = m.np
    maxh = m.maxh
    nbe = m.nb
    iw = clog2(nbe + 1)
    ports = emitter_ports(m)
    drops = emitter_drops?(m)

    val = fn inst, _c, fname ->
      f = Layer.field(layer_of(m, inst), fname)
      to_sv(evalue(m, inst, f), f.bits)
    end

    sel =
      for p <- m.paths do
        conds = Enum.map(p.conds, &cond_expr(m, &1, val))
        e = if conds == [], do: "1'b1", else: Enum.join(conds, "\n      && ")
        "  // path #{p.id}: #{describe(m, p)}\n  assign sel[#{p.id}] = #{e};\n"
      end

    # computed fields per instance
    computed =
      for inst <- m.insts do
        l = layer_of(m, inst)
        n = iname(m, inst)

        rel =
          path_mux(
            "sel",
            16,
            Enum.map(m.paths, fn p ->
              case steps_of(p, inst) do
                nil -> nil
                st -> "16'd#{p.payload - st.start}"
              end
            end)
          )

        lens =
          for f <- l.fields, f.length != nil do
            "  logic [#{f.bits - 1}:0] c_#{n}_#{f.name};\n" <>
              "  assign c_#{n}_#{f.name} = #{f.bits}'(rel_#{n} + payload_bytes);\n"
          end

        csum =
          case Enum.find(l.fields, &(&1.checksum == :header)) do
            nil -> ""
            f -> emitter_header_csum(m, inst, f)
          end

        rel_decl =
          if lens != [], do: "  logic [15:0] rel_#{n};\n  assign rel_#{n} = #{rel};\n", else: ""

        rel_decl <> Enum.join(lens) <> csum
      end

    # header bytes
    hbytes =
      for j <- 0..(maxh - 1) do
        exprs =
          Enum.map(m.paths, fn p ->
            case Enum.find(p.steps, &(&1.start <= j and j < &1.start + &1.hlen)) do
              nil -> nil
              st -> layer_byte(m, st.inst, j - st.start, &evalue(m, st.inst, &1))
            end
          end)

        "  assign hb[#{8 * j + 7}:#{8 * j}] = #{path_mux("sel", 8, exprs)};\n"
      end

    words =
      for wi <- 0..(nbe - 1) do
        lo = wi * k

        bytes =
          for b <- (lo + k - 1)..lo//-1,
              do: if(b < maxh, do: "hb[#{8 * b + 7}:#{8 * b}]", else: "8'h0")

        "      #{iw}'d#{wi}: hdr_word = #{concat(bytes)};\n"
      end

    hw_sel = path_mux("sel", iw, Enum.map(m.paths, &"#{iw}'d#{div(&1.payload, k)}"))
    s_sel = path_mux("sel", 8, Enum.map(m.paths, &"8'd#{rem(&1.payload, k)}"))

    mixed =
      for s <- 1..(k - 1)//1 do
        "      8'd#{s}: mixed = {s_axis_tdata[#{w - 8 * s - 1}:0], hdr_word[#{8 * s - 1}:0]};\n"
      end

    drop_logic =
      if drops do
        """
                  end else if (s_axis_tvalid) begin
                    // no header layout for these meta values
                    dropped_packets <= dropped_packets + 32'd1;
                    if (!s_axis_tlast) state <= E_DROP;
        """
      else
        ""
      end

    tuser =
      if m.tuser do
        "  assign m_axis_tuser = m_axis_tlast && ((state == E_FLUSH) ? tuser_q : s_axis_tuser);\n"
      else
        ""
      end

    """
    #{@header}
    module #{spec.name}_emitter (
      input  logic        clk,
      input  logic        rst_n,

      // AXI4-Stream slave: payload only
      // AXI4-Stream master: complete packets
    #{axis_ports(m, m.tuser, m.tuser, ports != [])}
      // Header fields, sampled while the first payload beat is pending
    #{port_decls(ports) |> Enum.join() |> String.trim_trailing(",\n")}
    );
      /* verilator lint_off UNUSEDSIGNAL */
      typedef enum logic [1:0] {E_HEADER = 2'd0, E_PAYLOAD = 2'd1, E_FLUSH = 2'd2, E_DROP = 2'd3} state_t;
      state_t state;

      logic [#{np - 1}:0] sel;
      logic        any_sel;
      logic [#{8 * maxh - 1}:0] hb;           // header byte j at [8j +: 8]
      logic [#{iw - 1}:0] word_idx, hw_sel;
      logic [7:0]  s_sel, keep_cnt, sh_q, flush_n_q, n_avail, n_out;
      logic [#{w - 1}:0] hdr_word, mixed, prev, shifted, cur;
      logic [#{2 * w - 1}:0] cat;
      logic        in_hdr, in_mixed, out_last, go_flush, tuser_q;

    #{sel}  assign any_sel = |sel;
    #{computed}
    #{hbytes}
      always_comb begin
        case (word_idx)
    #{words}      default: hdr_word = '0;
        endcase
      end

      assign hw_sel = #{hw_sel};
      assign s_sel  = #{s_sel};
      assign keep_cnt = #{keep_count(k)};

      // first payload beat after a header that ends mid-beat
      always_comb begin
        case (s_sel)
    #{mixed}      default: mixed = s_axis_tdata;
        endcase
      end

      assign cur = (state == E_FLUSH) ? '0 : s_axis_tdata;
      assign cat = {cur, prev};
      always_comb begin
        case (sh_q)
    #{for j <- 1..k, do: "      8'd#{j}: shifted = cat[#{8 * j + w - 1}:#{8 * j}];\n"}      default: shifted = cat[#{2 * w - 1}:#{w}];
        endcase
      end

      assign in_hdr   = (state == E_HEADER) && (word_idx < hw_sel);
      assign in_mixed = (state == E_HEADER) && !(word_idx < hw_sel);

      always_comb begin
        if (state == E_FLUSH) n_avail = flush_n_q;
        else if (in_mixed) n_avail = s_sel + (s_axis_tlast ? keep_cnt : 8'd#{k});
        else n_avail = 8'd#{k} - sh_q + (s_axis_tlast ? keep_cnt : 8'd#{k});
        n_out = in_hdr ? 8'd#{k} : ((n_avail > 8'd#{k}) ? 8'd#{k} : n_avail);
        out_last = !in_hdr && ((state == E_FLUSH) || s_axis_tlast) && (n_avail <= 8'd#{k});
        go_flush = !in_hdr && (state != E_FLUSH) && s_axis_tlast && (n_avail > 8'd#{k});
      end

      // Header beats are only offered once payload is pending, so tvalid never
      // depends on tready and the meta inputs belong to that payload.
      assign m_axis_tvalid = ((state == E_HEADER) && s_axis_tvalid && any_sel)
                          || ((state == E_PAYLOAD) && s_axis_tvalid) || (state == E_FLUSH);
      assign s_axis_tready = (state == E_HEADER) ? (any_sel ? (!in_hdr && m_axis_tready) : 1'b1)
                           : (state == E_PAYLOAD) ? m_axis_tready
                           : (state == E_DROP);
      assign m_axis_tdata  = in_hdr ? hdr_word : (in_mixed ? mixed : shifted);
    #{for l <- 0..(k - 1), do: "  assign m_axis_tkeep[#{l}] = (n_out > 8'd#{l});\n"}  assign m_axis_tlast  = out_last;
    #{tuser}
      always_ff @(posedge clk) begin
        if (!rst_n) begin
          state    <= E_HEADER;
          word_idx <= '0;
    #{if drops, do: "      dropped_packets <= '0;\n"}    end else begin
          case (state)
            E_HEADER: begin
              if (any_sel) begin
                if (s_axis_tvalid && m_axis_tready) begin
                  if (in_hdr) begin
                    word_idx <= word_idx + #{iw}'d1;
                    if (word_idx + #{iw}'d1 == hw_sel && s_sel == 8'd0) begin
                      word_idx <= '0;
                      state    <= E_PAYLOAD;
                    end
                  end else begin
                    word_idx <= '0;
                    if (out_last) state <= E_HEADER;
                    else if (go_flush) state <= E_FLUSH;
                    else state <= E_PAYLOAD;
                  end
                end
    #{drop_logic}          end
            end
            E_PAYLOAD: begin
              if (s_axis_tvalid && m_axis_tready) begin
                if (out_last) state <= E_HEADER;
                else if (go_flush) state <= E_FLUSH;
              end
            end
            E_FLUSH: if (m_axis_tready) state <= E_HEADER;
            default: if (s_axis_tvalid && s_axis_tlast) state <= E_HEADER;
          endcase
        end
      end

      // datapath registers (no reset needed, qualified by state)
      always_ff @(posedge clk) begin
        if (s_axis_tvalid && s_axis_tready) begin
          prev    <= s_axis_tdata;
          tuser_q <= #{if m.tuser, do: "s_axis_tuser", else: "1'b0"};
        end
        if (state == E_HEADER && s_axis_tvalid && m_axis_tready && any_sel) begin
          if (in_hdr) sh_q <= 8'd#{k};
          else sh_q <= 8'd#{k} - s_sel;
        end
        if (s_axis_tvalid && m_axis_tready && go_flush) flush_n_q <= n_avail - 8'd#{k};
      end
      /* verilator lint_on UNUSEDSIGNAL */
    endmodule
    """
    |> tidy()
  end

  # Value of a field in the emitter.
  defp evalue(m, inst, %Field{} = f) do
    cond do
      f.assert != nil -> {:lit, f.assert}
      f.length != nil -> "c_#{iname(m, inst)}_#{f.name}"
      f.checksum == :header -> "c_#{iname(m, inst)}_#{f.name}"
      true -> "#{prefix(m, inst)}#{f.name}"
    end
  end

  # Byte r of a layer instance's header, from field value expressions.
  defp layer_byte(m, inst, r, value) do
    l = layer_of(m, inst)

    cond do
      r >= l.fixed_bytes ->
        f = Layer.field(l, l.tail)
        i = r - l.fixed_bytes
        slice(value.(f), 8 * tail_bytes(m, inst), 8 * i + 7, 8 * i)

      m.spec.byte_order == :little ->
        f =
          Enum.find(
            l.fields,
            &(&1.kind != :bytes and &1.offset <= 8 * r and 8 * r < &1.offset + &1.bits)
          )

        lo = 8 * r - f.offset
        slice(value.(f), f.bits, lo + 7, lo)

      true ->
        parts =
          for f <- l.fields,
              f.kind != :bytes,
              a = max(f.offset, 8 * r),
              b = min(f.offset + f.bits, 8 * r + 8),
              a < b do
            hi = f.bits - 1 - (a - f.offset)
            lo = f.bits - 1 - (b - 1 - f.offset)
            slice(value.(f), f.bits, hi, lo)
          end

        concat(parts)
    end
  end

  defp emitter_header_csum(m, inst, cf) do
    l = layer_of(m, inst)
    n = iname(m, inst)
    {_, max} = Layer.size_range(l)

    hl =
      case l.hlen_field do
        nil ->
          "16'd#{l.fixed_bytes}"

        hf ->
          f = Layer.field(l, hf)
          "(16'(#{to_sv(evalue(m, inst, f), f.bits)}) * 16'd#{f.header_length})"
      end

    value = fn f -> if f == cf, do: {:lit, 0}, else: evalue(m, inst, f) end

    byte = fn r ->
      if r >= max do
        "8'h0"
      else
        b = layer_byte(m, inst, r, value)
        if r >= l.fixed_bytes, do: "((16'd#{r} < hl_#{n}) ? #{b} : 8'h0)", else: b
      end
    end

    words =
      for j <- 0..(div(max + 1, 2) - 1), do: "24'({#{byte.(2 * j)}, #{byte.(2 * j + 1)}})"

    """
      logic [15:0] hl_#{n};
      logic [23:0] hsum_#{n};
      logic [16:0] hf1_#{n};
      logic [15:0] hf2_#{n}, c_#{n}_#{cf.name};
      assign hl_#{n}   = #{hl};
      assign hsum_#{n} = #{Enum.join(words, "\n      + ")};
      assign hf1_#{n}  = 17'(hsum_#{n}[15:0]) + 17'(hsum_#{n}[23:16]);
      assign hf2_#{n}  = hf1_#{n}[15:0] + 16'(hf1_#{n}[16]);
      assign c_#{n}_#{cf.name} = ~hf2_#{n};
    """
  end

  # -- loopback ----------------------------------------------------------------

  defp loopback(m, opts) do
    spec = m.spec
    w = spec.bus_width
    k = m.k
    tables = Map.new(Keyword.get(opts, :match, %{}))

    pports = parser_ports(m)

    wires =
      for {name, dir, bits, signed} <- pports,
          dir == :output,
          name != "dropped_packets",
          do: "  #{sv_type(bits, signed)} #{name};\n"

    ties = match_ties(m, tables)

    parser_meta =
      for {name, :output, _, _} <- pports,
          name != "dropped_packets",
          do: "    .#{name}(#{name}),\n"

    emitter_meta =
      for {name, :input, _, _} <- emitter_inputs(m), do: "    .#{name}(#{name}),\n"

    plen = if m.lengths, do: "    .payload_bytes(meta_payload_bytes),\n", else: ""
    edrop = if emitter_drops?(m), do: "    .dropped_packets(emitter_dropped),\n", else: ""

    {pu, eu, mu} =
      if m.tuser,
        do: {".m_axis_tuser(p_tuser), ", ".s_axis_tuser(p_tuser), ", ".m_axis_tuser, "},
        else: {"", "", ""}

    """
    #{@header}
    // Parser -> emitter. Valid packets come out canonical (computed fields
    // recomputed, padding removed), bad ones are dropped and counted.
    module #{spec.name}_loopback (
      input  logic        clk,
      input  logic        rst_n,

    #{axis_ports(m, false, m.tuser)}
      output logic [31:0] dropped_packets
    );
      logic [#{w - 1}:0] p_tdata;
      logic [#{k - 1}:0] p_tkeep;
      logic        p_tlast, p_tvalid, p_tready#{if m.tuser, do: ", p_tuser"};

      // Asserted and computed fields and meta_valid are not needed by the emitter.
      /* verilator lint_off UNUSEDSIGNAL */
    #{wires}#{if emitter_drops?(m), do: "  logic [31:0] emitter_dropped;\n"}  /* verilator lint_on UNUSEDSIGNAL */

      #{spec.name}_parser u_parser (
        .clk, .rst_n,
        .s_axis_tdata, .s_axis_tkeep, .s_axis_tlast, .s_axis_tvalid, .s_axis_tready,
        .m_axis_tdata(p_tdata), .m_axis_tkeep(p_tkeep), .m_axis_tlast(p_tlast), #{pu}
        .m_axis_tvalid(p_tvalid), .m_axis_tready(p_tready),
    #{ties}#{parser_meta}    .dropped_packets
      );

      #{spec.name}_emitter u_emitter (
        .clk, .rst_n,
    #{emitter_meta}#{plen}#{edrop}    .s_axis_tdata(p_tdata), .s_axis_tkeep(p_tkeep), .s_axis_tlast(p_tlast), #{eu}
        .s_axis_tvalid(p_tvalid), .s_axis_tready(p_tready),
        .m_axis_tdata, .m_axis_tkeep, .m_axis_tlast, #{mu}.m_axis_tvalid, .m_axis_tready
      );
    endmodule
    """
    |> tidy()
  end

  # Constant match tables for the loopback and rx tops.
  defp match_ties(m, tables) do
    spec = m.spec

    for {inst, f} <- match_fields(m) do
      base = "match_#{iname(m, inst)}_#{f.name}"
      ref = Spec.ref(spec, elem(inst, 0), f.name)
      values = tables |> Map.get(ref, []) |> Enum.map(&Spec.resolve_value!(spec.name, f, &1))

      if length(values) > f.match,
        do:
          raise(
            ArgumentError,
            "#{inspect(ref)}: #{length(values)} values for #{f.match} entries"
          )

      entries =
        for e <- (f.match - 1)..0//-1,
            do: lit(Enum.at(values, e, 0), f.bits)

      en = for e <- (f.match - 1)..0//-1, do: if(e < length(values), do: "1'b1", else: "1'b0")

      "    .#{base}({#{Enum.join(entries, ", ")}}),\n    .#{base}_en({#{Enum.join(en, ", ")}}),\n"
    end
  end

  @doc """
  `<name>_rx`: the parser alone with constant match tables (`match:` as in
  `generate/2`) and the meta outputs left open, with the port set of the
  AXI4-Stream co-simulation harness. Returns `{filename, source}`.
  """
  def rx_top(%Spec{} = spec, opts \\ []) do
    m = model(spec)
    tables = Map.new(Keyword.get(opts, :match, %{}))
    ties = match_ties(m, tables)
    user = if m.tuser, do: ".m_axis_tuser, ", else: ""

    src =
      """
      #{@header}
      // Parser only, for throughput and payload checks.
      module #{spec.name}_rx (
        input  logic        clk,
        input  logic        rst_n,

      #{axis_ports(m, false, m.tuser)}
        output logic [31:0] dropped_packets
      );
        /* verilator lint_off PINCONNECTEMPTY */
        #{spec.name}_parser u_parser (
          .clk, .rst_n,
          .s_axis_tdata, .s_axis_tkeep, .s_axis_tlast, .s_axis_tvalid, .s_axis_tready,
          .m_axis_tdata, .m_axis_tkeep, .m_axis_tlast, #{user}.m_axis_tvalid, .m_axis_tready,
      #{ties}#{for {name, :output, _, _} <- parser_ports(m), name != "dropped_packets", do: "    .#{name}(),\n"}    .dropped_packets
        );
        /* verilator lint_on PINCONNECTEMPTY */
      endmodule
      """
      |> tidy()

    {"#{spec.name}_rx.sv", src}
  end

  # -- helpers -----------------------------------------------------------------

  # Bits hi..lo of a value: a signal name or {:lit, integer}.
  defp slice({:lit, x}, bits, hi, lo) do
    x = band(x, bsl(1, bits) - 1)
    lit(band(bsr(x, lo), bsl(1, hi - lo + 1) - 1), hi - lo + 1)
  end

  defp slice(v, 1, 0, 0), do: v
  defp slice(v, _bits, hi, hi), do: "#{v}[#{hi}]"
  defp slice(v, _bits, hi, lo), do: "#{v}[#{hi}:#{lo}]"

  defp to_sv({:lit, x}, bits), do: lit(x, bits)
  defp to_sv(v, _bits), do: v

  defp lit(v, bits) when v < 0, do: lit(v + bsl(1, bits), bits)
  defp lit(v, bits), do: "#{bits}'h#{hex(v)}"

  defp hex(v), do: Integer.to_string(v, 16)

  defp clog2(n), do: max(1, ceil_log2(n))
  defp ceil_log2(n), do: if(n <= 1, do: 0, else: 1 + ceil_log2(div(n + 1, 2)))

  # Drop blank lines left by empty template sections.
  defp tidy(src), do: String.replace(src, ~r/\n{3,}/, "\n\n")
end
