defmodule ExHdl.Backends.SystemVerilog.Protocol do
  @moduledoc """
  Emits synthesizable SystemVerilog-2012 for a `ExHdl.Protocol.Spec`:

    * `<name>_parser` - AXI4-Stream slave that strips and validates the header,
      exposes the fields as `meta_*` (stable while `meta_valid` is high, i.e.
      for the whole payload) and forwards the payload with full backpressure.
      Packets that fail an assertion, have a partial `tkeep` inside the header,
      end inside the header, or carry no payload are dropped up to `tlast` and
      counted in `dropped_packets`.
    * `<name>_emitter` - prepends a header built from `meta_*` to a payload
      stream. `meta_*` is sampled while the first payload beat is pending
      (`s_axis_tvalid` high), so it must be stable from then until that beat
      is accepted.
    * `<name>_loopback` - parser feeding emitter, used for co-simulation.

  The payload path is combinational (no bubble, line rate); `tvalid` never
  depends on `tready`.
  """

  import Bitwise
  alias ExHdl.Protocol.Spec

  @header "// Generated by ExHdl from defpacket. Do not edit.\n"

  @doc "Returns `%{filename => source}` for all modules of the spec."
  def generate(%Spec{} = spec) do
    %{
      "#{spec.name}_parser.sv" => parser(spec),
      "#{spec.name}_emitter.sv" => emitter(spec),
      "#{spec.name}_loopback.sv" => loopback(spec)
    }
  end

  # -- parser ------------------------------------------------------------------

  def parser(%Spec{} = spec) do
    w = spec.bus_width
    k = div(w, 8)
    h = Spec.header_words(spec)
    hbits = spec.header_bits
    iw = idx_width(h)

    meta_ports =
      Enum.map(spec.fields, fn f -> "  output logic #{sv_type(f)} meta_#{f.name},\n" end)

    field_wires =
      Enum.map(spec.fields, fn f ->
        "  logic #{sv_type(f)} hdr_#{f.name};\n  assign hdr_#{f.name} = #{extract(spec, f)};\n"
      end)

    checks =
      for f <- spec.fields,
          f.assert != nil,
          do: " && (hdr_#{f.name} == #{literal(f.assert, f.bits)})"

    keep_ok = if h > 1, do: "!hdr_keep_bad && !keep_bad", else: "!keep_bad"

    meta_latch = Enum.map(spec.fields, fn f -> "      meta_#{f.name} <= hdr_#{f.name};\n" end)

    {multi_decl, multi_assign, flat_assign, header_beat, multi_reset, shift_block} =
      if h > 1 do
        qbits = (h - 1) * w
        shift = if h == 2, do: "s_axis_tdata", else: "{s_axis_tdata, hdr_q[#{qbits - 1}:#{w}]}"

        {
          """
            logic [#{iw - 1}:0] word_idx;
            logic [#{qbits - 1}:0] hdr_q;        // header words 0..#{h - 2}, word 0 in the LSBs
            logic        hdr_keep_bad;           // an earlier header beat had a partial tkeep
          """,
          "  assign last_hdr_word = (word_idx == #{iw}'d#{h - 1});\n",
          "  assign hdr_flat = {s_axis_tdata, hdr_q};\n",
          indent(
            """
            if (last_hdr_word) begin
              word_idx     <= '0;
              hdr_keep_bad <= 1'b0;
            #{indent(accept_or_drop(), 2)}end else if (s_axis_tlast) begin
              // Runt: packet ended inside the header.
              word_idx        <= '0;
              hdr_keep_bad    <= 1'b0;
              dropped_packets <= dropped_packets + 32'd1;
            end else begin
              word_idx     <= word_idx + #{iw}'d1;
              hdr_keep_bad <= hdr_keep_bad | keep_bad;
            end
            """,
            8
          ),
          "      word_idx        <= '0;\n      hdr_keep_bad    <= 1'b0;\n",
          """

            // Header shift register (no reset needed, qualified by word_idx).
            always_ff @(posedge clk) begin
              if (state == S_HEADER && s_axis_tvalid && !last_hdr_word) begin
                hdr_q <= #{shift};
              end
            end
          """
        }
      else
        {"", "  assign last_hdr_word = 1'b1;\n", "  assign hdr_flat = s_axis_tdata;\n",
         indent(accept_or_drop(), 8), "", ""}
      end

    big_endian_view =
      if spec.byte_order == :big do
        "  logic [#{hbits - 1}:0] hdr_be;          // header as big-endian bitstream\n" <>
          "  assign hdr_be = #{byte_reverse("hdr_flat", hbits)};\n"
      else
        ""
      end

    """
    #{@header}
    module #{spec.name}_parser (
      input  logic        clk,
      input  logic        rst_n,

      // AXI4-Stream slave: complete packets
      input  logic [#{w - 1}:0] s_axis_tdata,
      input  logic [#{k - 1}:0] s_axis_tkeep,
      input  logic        s_axis_tlast,
      input  logic        s_axis_tvalid,
      output logic        s_axis_tready,

      // AXI4-Stream master: payload only
      output logic [#{w - 1}:0] m_axis_tdata,
      output logic [#{k - 1}:0] m_axis_tkeep,
      output logic        m_axis_tlast,
      output logic        m_axis_tvalid,
      input  logic        m_axis_tready,

      // Header fields, stable while meta_valid is high
      output logic        meta_valid,
    #{meta_ports}
      output logic [31:0] dropped_packets
    );
      typedef enum logic [1:0] {S_HEADER = 2'd0, S_PAYLOAD = 2'd1, S_DROP = 2'd2} state_t;
      state_t state;

    #{multi_decl}  logic        last_hdr_word;
      logic        keep_bad;
      logic        hdr_ok;
      logic [#{hbits - 1}:0] hdr_flat;        // header byte k at [8k +: 8], valid in the last header beat

    #{multi_assign}  assign keep_bad = (s_axis_tkeep != #{k}'h#{hex(bsl(1, k) - 1)});
    #{flat_assign}#{big_endian_view}
    #{field_wires}
      assign hdr_ok = #{keep_ok}#{checks};

      // Payload passthrough
      assign s_axis_tready = (state == S_PAYLOAD) ? m_axis_tready : 1'b1;
      assign m_axis_tvalid = (state == S_PAYLOAD) && s_axis_tvalid;
      assign m_axis_tdata  = s_axis_tdata;
      assign m_axis_tkeep  = s_axis_tkeep;
      assign m_axis_tlast  = s_axis_tlast;

      always_ff @(posedge clk) begin
        if (!rst_n) begin
          state           <= S_HEADER;
          meta_valid      <= 1'b0;
          dropped_packets <= '0;
    #{multi_reset}    end else begin
          case (state)
            S_HEADER: begin
              if (s_axis_tvalid) begin
    #{indent(header_beat, 4)}          end
            end
            S_PAYLOAD: begin
              if (s_axis_tvalid && m_axis_tready && s_axis_tlast) begin
                state      <= S_HEADER;
                meta_valid <= 1'b0;
              end
            end
            S_DROP: begin
              if (s_axis_tvalid && s_axis_tlast) state <= S_HEADER;
            end
            default: state <= S_HEADER;
          endcase
        end
      end
    #{shift_block}
      // Header field registers (no reset needed, qualified by meta_valid).
      always_ff @(posedge clk) begin
        if (state == S_HEADER && s_axis_tvalid && last_hdr_word && hdr_ok && !s_axis_tlast) begin
    #{meta_latch}    end
      end
    endmodule
    """
    |> tidy()
  end

  defp accept_or_drop do
    """
    if (hdr_ok && !s_axis_tlast) begin
      state      <= S_PAYLOAD;
      meta_valid <= 1'b1;
    end else begin
      // Bad header, or header without payload.
      dropped_packets <= dropped_packets + 32'd1;
      if (!s_axis_tlast) state <= S_DROP;
    end
    """
  end

  # Indents every non-empty line by n spaces.
  defp indent(text, n) do
    pad = String.duplicate(" ", n)

    text
    |> String.split("\n")
    |> Enum.map_join("\n", fn
      "" -> ""
      line -> pad <> line
    end)
  end

  # -- emitter -----------------------------------------------------------------

  def emitter(%Spec{} = spec) do
    w = spec.bus_width
    k = div(w, 8)
    h = Spec.header_words(spec)
    hbits = spec.header_bits
    iw = idx_width(h)

    meta_ports =
      for f <- spec.fields, f.assert == nil, do: "  input  logic #{sv_type(f)} meta_#{f.name},\n"

    values =
      Enum.map(spec.fields, fn
        %{assert: nil} = f -> "meta_#{f.name}"
        f -> literal(f.assert, f.bits)
      end)

    flat =
      case spec.byte_order do
        :little ->
          "{#{values |> Enum.reverse() |> Enum.join(", ")}}"

        :big ->
          byte_reverse("hdr_be", hbits)
      end

    be_decl =
      if spec.byte_order == :big,
        do:
          "  logic [#{hbits - 1}:0] hdr_be;          // header as big-endian bitstream\n" <>
            "  assign hdr_be = {#{Enum.join(values, ", ")}};\n",
        else: ""

    {idx_decl, word_mux, header_step, idx_reset} =
      if h > 1 do
        cases =
          for i <- 0..(h - 1),
              do: "      #{iw}'d#{i}: hdr_word = hdr_flat[#{(i + 1) * w - 1}:#{i * w}];\n"

        {
          "  logic [#{iw - 1}:0] word_idx;\n",
          """
            always_comb begin
              case (word_idx)
          #{cases}      default: hdr_word = '0;
              endcase
            end
          """,
          """
                  if (s_axis_tvalid && m_axis_tready) begin
                    if (word_idx == #{iw}'d#{h - 1}) begin
                      word_idx <= '0;
                      state    <= E_PAYLOAD;
                    end else begin
                      word_idx <= word_idx + #{iw}'d1;
                    end
                  end
          """,
          "      word_idx <= '0;\n"
        }
      else
        {"", "  assign hdr_word = hdr_flat;\n",
         "          if (s_axis_tvalid && m_axis_tready) state <= E_PAYLOAD;\n", ""}
      end

    """
    #{@header}
    module #{spec.name}_emitter (
      input  logic        clk,
      input  logic        rst_n,

      // Header fields, sampled while the first payload beat is pending
    #{meta_ports}
      // AXI4-Stream slave: payload only
      input  logic [#{w - 1}:0] s_axis_tdata,
      input  logic [#{k - 1}:0] s_axis_tkeep,
      input  logic        s_axis_tlast,
      input  logic        s_axis_tvalid,
      output logic        s_axis_tready,

      // AXI4-Stream master: complete packets
      output logic [#{w - 1}:0] m_axis_tdata,
      output logic [#{k - 1}:0] m_axis_tkeep,
      output logic        m_axis_tlast,
      output logic        m_axis_tvalid,
      input  logic        m_axis_tready
    );
      typedef enum logic {E_HEADER = 1'b0, E_PAYLOAD = 1'b1} state_t;
      state_t state;

    #{idx_decl}#{be_decl}  logic [#{hbits - 1}:0] hdr_flat;        // header byte k at [8k +: 8]
      logic [#{w - 1}:0] hdr_word;

      assign hdr_flat = #{flat};
    #{word_mux}
      // Header beats are only offered once payload is pending, so tvalid never
      // depends on tready and the meta inputs belong to that payload.
      assign m_axis_tvalid = s_axis_tvalid;
      assign s_axis_tready = (state == E_PAYLOAD) && m_axis_tready;
      assign m_axis_tdata  = (state == E_PAYLOAD) ? s_axis_tdata : hdr_word;
      assign m_axis_tkeep  = (state == E_PAYLOAD) ? s_axis_tkeep : '1;
      assign m_axis_tlast  = (state == E_PAYLOAD) && s_axis_tlast;

      always_ff @(posedge clk) begin
        if (!rst_n) begin
          state <= E_HEADER;
    #{idx_reset}    end else begin
          case (state)
            E_HEADER: begin
    #{header_step}        end
            E_PAYLOAD: begin
              if (s_axis_tvalid && m_axis_tready && s_axis_tlast) state <= E_HEADER;
            end
            default: state <= E_HEADER;
          endcase
        end
      end
    endmodule
    """
    |> tidy()
  end

  # -- loopback ----------------------------------------------------------------

  def loopback(%Spec{} = spec) do
    w = spec.bus_width
    k = div(w, 8)

    meta_wires = Enum.map(spec.fields, fn f -> "  logic #{sv_type(f)} meta_#{f.name};\n" end)
    parser_meta = Enum.map(spec.fields, fn f -> "    .meta_#{f.name}(meta_#{f.name}),\n" end)

    emitter_meta =
      for f <- spec.fields, f.assert == nil, do: "    .meta_#{f.name}(meta_#{f.name}),\n"

    """
    #{@header}
    // Parser -> emitter. Valid packets come out byte-identical, bad ones are
    // dropped and counted.
    module #{spec.name}_loopback (
      input  logic        clk,
      input  logic        rst_n,

      input  logic [#{w - 1}:0] s_axis_tdata,
      input  logic [#{k - 1}:0] s_axis_tkeep,
      input  logic        s_axis_tlast,
      input  logic        s_axis_tvalid,
      output logic        s_axis_tready,

      output logic [#{w - 1}:0] m_axis_tdata,
      output logic [#{k - 1}:0] m_axis_tkeep,
      output logic        m_axis_tlast,
      output logic        m_axis_tvalid,
      input  logic        m_axis_tready,

      output logic [31:0] dropped_packets
    );
      logic [#{w - 1}:0] p_tdata;
      logic [#{k - 1}:0] p_tkeep;
      logic        p_tlast, p_tvalid, p_tready;

      // Asserted fields and meta_valid are not needed by the emitter.
      /* verilator lint_off UNUSEDSIGNAL */
      logic        meta_valid;
    #{meta_wires}  /* verilator lint_on UNUSEDSIGNAL */

      #{spec.name}_parser u_parser (
        .clk, .rst_n,
        .s_axis_tdata, .s_axis_tkeep, .s_axis_tlast, .s_axis_tvalid, .s_axis_tready,
        .m_axis_tdata(p_tdata), .m_axis_tkeep(p_tkeep), .m_axis_tlast(p_tlast),
        .m_axis_tvalid(p_tvalid), .m_axis_tready(p_tready),
        .meta_valid,
    #{parser_meta}    .dropped_packets
      );

      #{spec.name}_emitter u_emitter (
        .clk, .rst_n,
    #{emitter_meta}    .s_axis_tdata(p_tdata), .s_axis_tkeep(p_tkeep), .s_axis_tlast(p_tlast),
        .s_axis_tvalid(p_tvalid), .s_axis_tready(p_tready),
        .m_axis_tdata, .m_axis_tkeep, .m_axis_tlast, .m_axis_tvalid, .m_axis_tready
      );
    endmodule
    """
    |> tidy()
  end

  # -- helpers -----------------------------------------------------------------

  # Expression selecting field `f` out of the parser's `hdr_flat`/`hdr_be`.
  defp extract(%Spec{byte_order: :little}, f),
    do: "hdr_flat[#{f.offset + f.bits - 1}:#{f.offset}]"

  defp extract(%Spec{byte_order: :big, header_bits: hbits}, f) do
    hi = hbits - 1 - f.offset
    "hdr_be[#{hi}:#{hi - f.bits + 1}]"
  end

  # Swaps the byte order of a `bits`-wide signal: {x[7:0], x[15:8], ...}.
  defp byte_reverse(sig, bits) do
    parts = for b <- 0..(div(bits, 8) - 1), do: "#{sig}[#{8 * b + 7}:#{8 * b}]"
    "{#{Enum.join(parts, ", ")}}"
  end

  defp sv_type(%{bits: bits, signed: true}), do: "signed [#{bits - 1}:0]"
  defp sv_type(%{bits: bits}), do: "[#{bits - 1}:0]"

  defp literal(v, bits) when v < 0, do: literal(v + bsl(1, bits), bits)
  defp literal(v, bits), do: "#{bits}'h#{hex(v)}"

  defp hex(v), do: Integer.to_string(v, 16)

  defp idx_width(words), do: max(1, ceil_log2(words))
  defp ceil_log2(n), do: if(n <= 1, do: 0, else: 1 + ceil_log2(div(n + 1, 2)))

  # Drop blank lines left by empty template sections.
  defp tidy(src), do: String.replace(src, ~r/\n{3,}/, "\n\n")
end
