defmodule ExHdl.Backends.SystemVerilog.RTL do
  @moduledoc """
  SystemVerilog-2012 for `ExHdl.RTL` modules: one file `<name>.sv` per
  module, lint-clean under `verilator --lint-only -Wall`.

    * Signals keep their names; instance ports become `<instance>_<port>`
      wires, memory read data `<memory>_rd<i>` unless named. Hoisted
      subexpressions (slices of expressions, list muxes) are `_t<n>`.
    * Every operation is written so SystemVerilog's context-dependent
      widths cannot change its value: operands are extended explicitly
      (`9'(a)`), and operations that can overflow carry a size cast of
      their own width. The value is the one `ExHdl.RTL.Expr.eval/3` defines.
    * Combinational logic: `assign` for a single unconditional assignment,
      else one `always_comb` per signal. Registers: one `always_ff` per
      domain for registers with reset, one for registers without.
    * Memories are emitted in the inference templates of Vivado and Yosys
      (an unpacked array, one `always_ff` per port, byte enables as
      per-byte conditional writes) with `(* ram_style = ... *)`;
      `ASYNC_REG` registers carry `(* ASYNC_REG = "TRUE" *)`.
    * Signals with bits nobody reads are wrapped in
      `verilator lint_off UNUSEDSIGNAL` pragmas. `UNSIGNED` and `CMPCONST`
      are off for the whole module: constant folding removes comparisons
      that are constant at the word level, but Verilator propagates
      constants bit by bit and still finds some (an index whose low bits
      are constant, for example), which is harmless. `VARHIDDEN` is off
      too: a child's signal may share a name with the parent's instance
      label, and labels stay as written so hierarchical paths (XDC, VCD)
      are predictable.
  """

  import Bitwise

  alias ExHdl.RTL.{Expr, Module, Stmt}

  @doc """
  Returns `%{filename => source}` for `mod` and every module below it, plus
  the `sources` attached to black boxes. Black boxes themselves are not
  emitted.

  Option `sim: true` adds the black boxes' `sim_sources` (simulation stubs
  of vendor primitives; they replace a `sources` file of the same name).
  Without it they are never returned, so synthesis does not see them.
  """
  @spec generate(Module.t(), keyword()) :: %{String.t() => String.t()}
  def generate(%Module{} = mod, opts \\ []) do
    sim = Keyword.get(opts, :sim, false)

    mod
    |> Module.hierarchy()
    |> Enum.reduce(%{}, fn
      %Module{kind: :black_box} = bb, acc ->
        acc |> Map.merge(bb.sources) |> Map.merge(if sim, do: bb.sim_sources, else: %{})

      m, acc ->
        Map.put(acc, "#{m.name}.sv", module_source(m))
    end)
  end

  @doc "The SystemVerilog source of one module (instances are referenced by name)."
  @spec module_source(Module.t()) :: String.t()
  def module_source(%Module{kind: :module} = m) do
    st = %{m: m, used: %{}, temps: [], n: 0, params_used: MapSet.new()}

    {comb, st} = Enum.map_reduce(m.comb, st, &comb_proc/2)
    {sync, st} = Enum.map_reduce(m.domains, st, &domain_blocks/2)
    {mems, st} = Enum.map_reduce(m.memories, st, &memory_blocks/2)
    {insts, st} = Enum.map_reduce(m.instances, st, &instance/2)

    # outputs are read outside
    st = Enum.reduce(Module.outputs(m), st, &use_all(&2, &1.name))

    IO.iodata_to_binary([
      "// Generated by ExHdl (ExHdl.RTL) from module #{m.name}. Do not edit.\n",
      "`default_nettype none\n",
      "/* verilator lint_off UNSIGNED */\n/* verilator lint_off CMPCONST */\n/* verilator lint_off VARHIDDEN */\n\n",
      attrs(m.attrs, ""),
      "module #{m.name} (\n",
      ports(m, st),
      ");\n",
      localparams(m),
      decls(m, st),
      mem_decls(m, st),
      temps(st),
      section(comb |> Enum.chunk_by(&is_binary/1) |> Enum.map(&chunk/1)),
      section(Enum.concat(sync)),
      section(Enum.concat(mems)),
      section(insts),
      "endmodule\n\n/* verilator lint_on VARHIDDEN */\n/* verilator lint_on CMPCONST */\n/* verilator lint_on UNSIGNED */\n",
      "`default_nettype wire\n"
    ])
  end

  defp section(blocks) do
    case Enum.reject(blocks, &(&1 == [] or &1 == "")) do
      [] -> []
      bs -> ["\n", Enum.intersperse(bs, "\n")]
    end
  end

  defp chunk([b | _] = assigns) when is_binary(b), do: assigns
  defp chunk(blocks), do: Enum.intersperse(blocks, "\n")

  defp attrs([], _ind), do: []

  defp attrs(kw, ind) do
    body = Enum.map_join(kw, ", ", fn {k, v} -> "#{k} = #{param_value(v)}" end)
    "#{ind}(* #{body} *)\n"
  end

  # -- declarations ----------------------------------------------------------------------

  @doc false
  def sv_type({:u, 1}), do: "logic"
  def sv_type({:s, 1}), do: "logic signed"
  def sv_type({:u, w}), do: "logic [#{w - 1}:0]"
  def sv_type({:s, w}), do: "logic signed [#{w - 1}:0]"

  defp ports(m, st) do
    tw = m.ports |> Enum.map(&String.length(sv_type(&1.type))) |> Enum.max(fn -> 5 end)
    last = length(m.ports) - 1

    m.ports
    |> Enum.with_index()
    |> Enum.map(fn {p, i} ->
      {dir, type} =
        case p.dir do
          :input -> {"input ", sv_type(p.type)}
          :output -> {"output", sv_type(p.type)}
          # a net: `default_nettype none` leaves `inout logic` without a net type
          :inout -> {"inout ", "wire" <> String.replace_prefix(sv_type(p.type), "logic", "")}
        end

      line =
        "  #{dir} #{String.pad_trailing(type, tw)} #{p.name}#{if i < last, do: ",", else: ""}\n"

      lint_wrap(line, unused?(st, p.name, p.type), "UNUSEDSIGNAL", "  ")
    end)
  end

  defp lint_wrap(line, false, _, _), do: line

  defp lint_wrap(line, true, warn, ind),
    do: [
      "#{ind}/* verilator lint_off #{warn} */\n",
      line,
      "#{ind}/* verilator lint_on #{warn} */\n"
    ]

  defp localparams(%{fsms: []}), do: []

  defp localparams(m) do
    lines =
      for f <- m.fsms, {s, code} <- f.states do
        t = f.state.type
        name = ExHdl.RTL.Builder.label_name(f.name, s)
        line = "  localparam #{sv_type(t)} #{name} = #{literal(code, t)};\n"
        line
      end

    [
      "\n",
      "  /* verilator lint_off UNUSEDPARAM */\n",
      lines,
      "  /* verilator lint_on UNUSEDPARAM */\n"
    ]
  end

  defp decls(m, st) do
    sigs =
      for n <- m.decls, s = m.signals[n], s.port == nil, s.kind not in [:clock, :reset] do
        attr = signal_attrs(s.attrs)
        line = "  #{attr}#{sv_type(s.type)} #{n};\n"
        lint_wrap(line, unused?(st, n, s.type), "UNUSEDSIGNAL", "  ")
      end

    if sigs == [], do: [], else: ["\n" | sigs]
  end

  defp signal_attrs(attrs) do
    user = Keyword.drop(attrs, [:async_reg, :cdc])
    all = if attrs[:async_reg], do: [ASYNC_REG: "TRUE"] ++ user, else: user

    case all do
      [] ->
        ""

      kw ->
        "(* " <> Enum.map_join(kw, ", ", fn {k, v} -> "#{k} = #{param_value(v)}" end) <> " *) "
    end
  end

  defp mem_decls(m, st) do
    for mem <- m.memories do
      style =
        if mem.style == :auto, do: "", else: "  (* ram_style = \"#{ram_style(mem.style)}\" *)\n"

      decl = "#{style}  logic [#{mem.width - 1}:0] #{mem.name} [0:#{mem.depth - 1}];\n"
      unused = not Map.has_key?(st.used, mem.name)
      multi = length(mem.write_ports) > 1
      decl = lint_wrap(decl, unused, "UNUSEDSIGNAL", "  ")
      decl = lint_wrap(decl, multi, "MULTIDRIVEN", "  ")

      init =
        if mem.init do
          lines =
            mem.init
            |> Enum.sort()
            |> Enum.map(fn {a, v} ->
              "    #{mem.name}[#{a}] = #{literal(v, {:u, mem.width})};\n"
            end)

          ["  initial begin\n", lines, "  end\n"]
        else
          []
        end

      ["\n", decl, init]
    end
  end

  defp ram_style(:block), do: "block"
  defp ram_style(:ultra), do: "ultra"
  defp ram_style(:distributed), do: "distributed"
  defp ram_style(:registers), do: "registers"

  defp temps(%{temps: []}), do: []

  defp temps(st) do
    ts = Enum.reverse(st.temps)

    decls =
      for {name, type, _} <- ts,
          do:
            lint_wrap(
              "  #{sv_type(type)} #{name};\n",
              unused?(st, name, type),
              "UNUSEDSIGNAL",
              "  "
            )

    defs = for {_, _, body} <- ts, do: body
    ["\n", decls, defs]
  end

  # -- usage tracking --------------------------------------------------------------------

  defp use_all(st, name), do: %{st | used: Map.put(st.used, name, :all)}

  defp use_bits(st, name, lo, w) do
    bits = MapSet.new(lo..(lo + w - 1))

    used =
      Map.update(st.used, name, bits, fn
        :all -> :all
        set -> MapSet.union(set, bits)
      end)

    %{st | used: used}
  end

  defp unused?(st, name, {_, w}) do
    case Map.get(st.used, name) do
      nil -> true
      :all -> false
      set -> MapSet.size(set) < w
    end
  end

  # -- literals --------------------------------------------------------------------------

  @doc false
  def literal(v, {:u, 1}), do: "1'b#{v}"
  def literal(v, {:s, 1}), do: "1'sb#{band(v, 1)}"
  def literal(v, {:u, w}) when v < 256, do: "#{w}'d#{v}"
  def literal(v, {:u, w}), do: "#{w}'h#{Integer.to_string(v, 16)}"
  def literal(v, {:s, w}) when v >= 0, do: "#{w}'sd#{v}"

  # Negative values in two's complement hex: a negated literal would be an
  # operator whose operand SystemVerilog may widen.
  def literal(v, {:s, w}), do: "#{w}'sh#{Integer.to_string(v + (1 <<< w), 16)}"

  defp param_value(v) when is_integer(v), do: Integer.to_string(v)
  defp param_value(v) when is_float(v), do: real(v)
  defp param_value({:real, v}) when is_number(v), do: real(v / 1)
  defp param_value(v) when is_binary(v), do: inspect(v)
  defp param_value({:bits, w, v}), do: "#{w}'h#{Integer.to_string(v, 16)}"
  defp param_value(true), do: "1"
  defp param_value(false), do: "0"

  # SV real literal: `2.5`, `10.0`, `1.0e-3` (shortest form that reads back).
  defp real(v), do: :erlang.float_to_binary(v, [:short])

  # -- expressions -----------------------------------------------------------------------

  @arith %{add: "+", sub: "-", mul: "*"}
  @bitwise %{and: "&", or: "|", xor: "^"}
  @compare %{eq: "==", ne: "!=", lt: "<", le: "<=", gt: ">", ge: ">="}

  # Top level of an assignment whose target has the expression's width:
  # no outer size cast needed.
  defp ex_top(%Expr{op: op, args: [a, b], type: {_, w}}, st) when is_map_key(@arith, op) do
    {sa, st} = ext(a, w, st)
    {sb, st} = ext(b, w, st)
    {"#{sa} #{@arith[op]} #{sb}", st}
  end

  defp ex_top(e, st) do
    {s, st} = ex(e, st)
    {strip_parens(s), st}
  end

  defp strip_parens("(" <> rest = s) do
    if String.ends_with?(rest, ")") and balanced?(String.slice(rest, 0..-2//1)),
      do: String.slice(rest, 0..-2//1),
      else: s
  end

  defp strip_parens(s), do: s

  defp balanced?(s) do
    s
    |> String.to_charlist()
    |> Enum.reduce_while(0, fn
      ?(, d -> {:cont, d + 1}
      ?), 0 -> {:halt, -1}
      ?), d -> {:cont, d - 1}
      _, d -> {:cont, d}
    end)
    |> Kernel.==(0)
  end

  # Operand `e` extended to `w` bits.
  defp ext(%Expr{op: :const, args: [v | _], type: {s, _}} = e, w, st) do
    if Expr.width(e) == w and length(e.args) == 2, do: ex(e, st), else: {literal(v, {s, w}), st}
  end

  # A widening cast makes Verilator size the operand's operators to the
  # cast width, so the operand gets its own size first.
  defp ext(e, w, st) do
    if Expr.width(e) == w do
      ex(e, st)
    else
      {s, st} = sized(e, st)
      {"#{w}'(#{s})", st}
    end
  end

  defp ex(%Expr{op: :sig, args: [n | _]}, st), do: {Atom.to_string(n), use_all(st, n)}
  defp ex(%Expr{op: :const, args: [_v, label]}, st), do: {label, st}
  defp ex(%Expr{op: :const, args: [v], type: t}, st), do: {literal(v, t), st}

  defp ex(%Expr{op: op, args: [a, b], type: {_, w}}, st) when is_map_key(@arith, op) do
    {sa, st} = ext(a, w, st)
    {sb, st} = ext(b, w, st)
    {"#{w}'(#{sa} #{@arith[op]} #{sb})", st}
  end

  defp ex(%Expr{op: :neg, args: [a], type: {_, w}}, st) do
    {sa, st} = ext(a, w, st)
    {"#{w}'(-#{unary_operand(sa)})", st}
  end

  defp ex(%Expr{op: op, args: [a, b], type: {_, w}}, st) when is_map_key(@bitwise, op) do
    {sa, st} = ext(a, w, st)
    {sb, st} = ext(b, w, st)
    {"(#{sa} #{@bitwise[op]} #{sb})", st}
  end

  defp ex(%Expr{op: :not, args: [a], type: {_, w}}, st) do
    {sa, st} = ex(a, st)
    {"#{w}'(~#{unary_operand(sa)})", st}
  end

  defp ex(%Expr{op: op, args: [a, b]}, st) when is_map_key(@compare, op) do
    w = max(Expr.width(a), Expr.width(b))
    {sa, st} = ext(a, w, st)
    {sb, st} = ext(b, w, st)
    {"(#{sa} #{@compare[op]} #{sb})", st}
  end

  defp ex(%Expr{op: :land, args: [a, b]}, st), do: bin("&&", a, b, st)
  defp ex(%Expr{op: :lor, args: [a, b]}, st), do: bin("||", a, b, st)

  defp ex(%Expr{op: :lnot, args: [a]}, st) do
    {sa, st} = ex(a, st)
    {"!#{sa}", st}
  end

  defp ex(%Expr{op: :reduce_and, args: [a]}, st), do: unary("&", a, st)
  defp ex(%Expr{op: :reduce_or, args: [a]}, st), do: unary("|", a, st)
  defp ex(%Expr{op: :reduce_xor, args: [a]}, st), do: unary("^", a, st)

  defp ex(%Expr{op: :shl, args: [a, n], type: {_, w}}, st) do
    {sa, st} = ext(a, w, st)
    {"#{w}'(#{sa} << #{n})", st}
  end

  # Verilator may turn a constant right shift of a signal into a select.
  defp ex(%Expr{op: :shr, args: [%Expr{op: :sig, args: [name | _]} = a, n]}, st) do
    w = Expr.width(a)
    st = if n < w, do: use_bits(st, name, n, w - n), else: st
    {"(#{name} #{if Expr.signed?(a), do: ">>>", else: ">>"} #{n})", st}
  end

  defp ex(%Expr{op: :shr, args: [a, n]}, st) do
    {sa, st} = sized(a, st)
    {"(#{sa} #{if Expr.signed?(a), do: ">>>", else: ">>"} #{n})", st}
  end

  defp ex(%Expr{op: :shl_dyn, args: [a, b], type: {_, w}}, st) do
    {sa, st} = ext(a, w, st)
    {sb, st} = ex(b, st)
    {"#{w}'(#{sa} << #{sb})", st}
  end

  defp ex(%Expr{op: :shr_dyn, args: [a, b]}, st) do
    {sa, st} = sized(a, st)
    {sb, st} = ex(b, st)
    {"(#{sa} #{if Expr.signed?(a), do: ">>>", else: ">>"} #{sb})", st}
  end

  defp ex(%Expr{op: :mux, args: [c, a, b], type: {_, w}}, st) do
    {sc, st} = ex(c, st)
    {sa, st} = ext(a, w, st)
    {sb, st} = ext(b, w, st)
    {"(#{sc} ? #{sa} : #{sb})", st}
  end

  defp ex(%Expr{op: :muxn, type: t} = e, st) do
    {name, st} = fresh(st)
    {body, st} = case_table(name, e, "", st)
    {name, st |> add_temp(name, t, body) |> use_all(name)}
  end

  defp ex(%Expr{op: :cat, args: [items]}, st) do
    {ss, st} = Enum.map_reduce(items, st, &ex/2)
    sep = if Enum.sum(Enum.map(ss, &String.length/1)) > 80, do: ",\n      ", else: ", "
    {"{#{Enum.join(ss, sep)}}", st}
  end

  defp ex(%Expr{op: :rep, args: [a, n]}, st) do
    {sa, st} = ex(a, st)
    {"{#{n}{#{sa}}}", st}
  end

  defp ex(%Expr{op: :slice, args: [a, lo, w]}, st) do
    {base, st} = named(a, st)
    aw = Expr.width(a)
    st = use_bits(st, base, lo, w)

    cond do
      lo == 0 and w == aw and Expr.signed?(a) -> {"$unsigned(#{base})", st}
      lo == 0 and w == aw -> {"#{base}", st}
      w == 1 -> {"#{base}[#{lo}]", st}
      true -> {"#{base}[#{lo + w - 1}:#{lo}]", st}
    end
  end

  defp ex(%Expr{op: :index, args: [a, i]}, st) do
    {base, st} = named(a, st)
    st = use_all(st, base)
    aw = Expr.width(a)
    iw = max(ExHdl.RTL.Builder.ceil_log2(aw), 1)
    wi = Expr.width(i)
    {si, st} = ex(i, st)

    cond do
      aw == 1 ->
        {"((#{si} == #{literal(0, i.type)}) ? #{base} : 1'b0)", st}

      wi == iw and 1 <<< iw == aw ->
        {"#{base}[#{si}]", st}

      wi < iw and 1 <<< iw == aw ->
        {"#{base}[#{iw}'(#{si})]", st}

      true ->
        cmp = max(wi, ExHdl.RTL.Builder.ceil_log2(aw + 1))
        {"((#{cmp}'(#{si}) < #{literal(aw, {:u, cmp})}) ? #{base}[#{iw}'(#{si})] : 1'b0)", st}
    end
  end

  # A truncating cast of a signal (possibly through $signed/$unsigned) reads
  # only its low bits, and Verilator tracks that.
  defp ex(%Expr{op: :resize, args: [a], type: {_, w}} = e, st) when w < a.type |> elem(1) do
    case cast_chain(a) do
      {:ok, name, text} -> {"#{w}'(#{text})", use_bits(st, name, 0, w)}
      :error -> resize(e, st)
    end
  end

  defp ex(%Expr{op: :resize} = e, st), do: resize(e, st)

  defp ex(%Expr{op: :mem_read, args: [mem, addr]}, st) do
    m = Enum.find(st.m.memories, &(&1.name == mem))
    {sa, st} = ex_top(addr, st)
    st = use_all(st, mem)

    if 1 <<< m.addr_width == m.depth,
      do: {"#{mem}[#{sa}]", st},
      else:
        {"((#{sa} < #{literal(m.depth, addr.type)}) ? #{mem}[#{sa}] : #{literal(0, {:u, m.width})})",
         st}
  end

  defp ex(%Expr{op: :cast, args: [a], type: {s, _}}, st) do
    {sa, st} = ex(a, st)
    {"#{cast_fn(s)}(#{strip_parens(sa)})", st}
  end

  defp case_table(name, %Expr{op: :muxn, args: [sel, items, default]}, case_attr, st) do
    {ssel, st} = ex(sel, st)

    {cases, st} =
      items
      |> Enum.with_index()
      |> Enum.map_reduce(st, fn {item, i}, st ->
        {si, st} = ex_top(item, st)
        {"      #{literal(i, sel.type)}: #{name} = #{si};\n", st}
      end)

    {sd, st} = ex_top(default, st)

    body = [
      "  always_comb begin\n",
      "    #{case_attr}case (#{ssel})\n",
      cases,
      "      default: #{name} = #{sd};\n",
      "    endcase\n",
      "  end\n"
    ]

    {body, st}
  end

  defp table(t, e, style, st) do
    attr = if style == "distributed", do: ~s|(* rom_style = "logic" *) |, else: ""
    case_table(t, e, attr, st)
  end

  defp resize(%Expr{args: [a], type: {_, w}}, st) do
    {sa, st} = if w > Expr.width(a), do: sized(a, st), else: ex(a, st)
    {"#{w}'(#{sa})", st}
  end

  # Yosys reads `-8'(x)` as a cast of negative size.
  defp unary_operand(sa) do
    sa = to_string(sa)
    if sa =~ ~r/^\d/, do: "(#{sa})", else: sa
  end

  defp cast_fn(:s), do: "$signed"
  defp cast_fn(:u), do: "$unsigned"

  defp cast_chain(%Expr{op: :sig, args: [n | _]}), do: {:ok, n, Atom.to_string(n)}

  defp cast_chain(%Expr{op: :cast, args: [a], type: {s, _}}) do
    with {:ok, n, text} <- cast_chain(a), do: {:ok, n, "#{cast_fn(s)}(#{text})"}
  end

  # A full-width slice is emitted as the signal itself.
  defp cast_chain(%Expr{op: :slice, args: [a, 0, w]}) do
    with true <- w == Expr.width(a), {:ok, n, text} <- cast_chain(a) do
      {:ok, n, if(Expr.signed?(a), do: "$unsigned(#{text})", else: text)}
    else
      _ -> :error
    end
  end

  defp cast_chain(_), do: :error

  # The shifted operand of a right shift gets an explicit size: Verilator
  # sizes it from both shift operands otherwise.
  defp sized(%Expr{op: op} = a, st) when op in [:sig, :const], do: ex(a, st)

  defp sized(a, st) do
    {sa, st} = ex(a, st)
    sa = to_string(sa)
    w = Expr.width(a)
    if String.starts_with?(sa, "#{w}'("), do: {sa, st}, else: {"#{w}'(#{sa})", st}
  end

  defp bin(op, a, b, st) do
    {sa, st} = ex(a, st)
    {sb, st} = ex(b, st)
    {"(#{sa} #{op} #{sb})", st}
  end

  defp unary(op, a, st) do
    {sa, st} = ex(a, st)
    {"(#{op}#{sa})", st}
  end

  # A signal name for `e`: itself if it is a signal, else a hoisted temp.
  defp named(%Expr{op: :sig, args: [n | _]}, st), do: {n, st}

  defp named(e, st) do
    {name, st} = fresh(st)
    {s, st} = ex_top(e, st)
    {name, add_temp(st, name, e.type, "  assign #{name} = #{s};\n")}
  end

  defp fresh(st), do: {:"_t#{st.n}", %{st | n: st.n + 1}}

  defp add_temp(st, name, type, body), do: %{st | temps: [{name, type, body} | st.temps]}

  # -- statements ------------------------------------------------------------------------

  # A table with a ROM style is written into its signal (whose declaration
  # carries `rom_style` for Vivado); `distributed` also marks the case
  # `rom_style = "logic"`, which keeps Yosys from merging it into block RAM.
  defp comb_proc({t, [{:assign, t, %Expr{op: :muxn} = e}]} = proc, st) do
    case Keyword.get(st.m.signals[t].attrs, :rom_style) do
      nil -> comb_assign(proc, st)
      style -> table(t, e, style, st)
    end
  end

  defp comb_proc({_t, [{:assign, _, _}]} = proc, st), do: comb_assign(proc, st)

  defp comb_proc({_t, stmts}, st) do
    {body, st} = stmts(stmts, "=", 2, st)
    {["  always_comb begin\n", body, "  end\n"], st}
  end

  defp comb_assign({t, [{:assign, t, e}]}, st) do
    {s, st} = ex_top(e, st)
    {"  assign #{t} = #{s};\n", st}
  end

  defp stmts(list, op, depth, st), do: Enum.map_reduce(list, st, &stmt(&1, op, depth, &2))

  defp stmt({:assign, t, e}, op, depth, st) do
    {s, st} = ex_top(e, st)
    {"#{ind(depth)}#{t} #{op} #{s};\n", st}
  end

  defp stmt({:if, c, a, b}, op, depth, st) do
    {sc, st} = ex_top(c, st)
    {sa, st} = stmts(a, op, depth + 1, st)
    head = ["#{ind(depth)}if (#{sc}) begin\n", sa]

    case b do
      [] ->
        {[head, "#{ind(depth)}end\n"], st}

      [{:if, _, _, _} = elif] ->
        {[_ | rest], st} = stmt_list_inline(elif, op, depth, st)
        {[head, "#{ind(depth)}end else " | rest], st}

      _ ->
        {sb, st} = stmts(b, op, depth + 1, st)
        {[head, "#{ind(depth)}end else begin\n", sb, "#{ind(depth)}end\n"], st}
    end
  end

  defp stmt({:switch, subj, cases, default}, op, depth, st) do
    {ss, st} = ex_top(subj, st)

    {items, st} =
      Enum.map_reduce(cases, st, fn {vals, body}, st ->
        {vs, st} = Enum.map_reduce(vals, st, &ex/2)
        {b, st} = case_body(body, op, depth + 1, st)
        {["#{ind(depth + 1)}#{Enum.join(vs, ", ")}:", b], st}
      end)

    {d, st} = case_body(default || [], op, depth + 1, st)

    {[
       "#{ind(depth)}case (#{ss})\n",
       items,
       "#{ind(depth + 1)}default:",
       d,
       "#{ind(depth)}endcase\n"
     ], st}
  end

  # An `if` whose text starts on the current line (for `else if`).
  defp stmt_list_inline(s, op, depth, st) do
    {text, st} = stmt(s, op, depth, st)
    text = IO.iodata_to_binary(text)
    {[:skip, String.trim_leading(text)], st}
  end

  defp case_body([], _op, _depth, st), do: {" ;\n", st}

  defp case_body([{:assign, _, _} = s], op, depth, st) do
    {text, st} = stmt(s, op, depth, st)
    {[" ", String.trim_leading(IO.iodata_to_binary(text))], st}
  end

  defp case_body(body, op, depth, st) do
    {b, st} = stmts(body, op, depth + 1, st)
    {[" begin\n", b, "#{ind(depth)}end\n"], st}
  end

  defp ind(depth), do: String.duplicate("  ", depth)

  # -- registers -------------------------------------------------------------------------

  defp domain_blocks(d, st) do
    m = st.m
    stmts = Keyword.get(m.sync, d.name, [])
    regs = for n <- m.decls, s = m.signals[n], s.kind == :reg, s.domain == d.name, do: s
    {with_reset, plain} = Enum.split_with(regs, &(&1.reset != nil))
    clk = hd(d.clock.args)

    {a, st} =
      if with_reset == [] do
        {[], st}
      else
        rst = hd(d.reset.args)
        st = st |> use_all(clk) |> use_all(rst)
        names = MapSet.new(with_reset, & &1.name)
        {body, st} = stmts(Stmt.slice(stmts, names), "<=", 3, st)

        sens =
          case {d.reset_kind, d.reset_active} do
            {:sync, _} -> "posedge #{clk}"
            {:async, :low} -> "posedge #{clk} or negedge #{rst}"
            {:async, :high} -> "posedge #{clk} or posedge #{rst}"
          end

        cond_ = if d.reset_active == :low, do: "!#{rst}", else: "#{rst}"
        resets = for r <- with_reset, do: "      #{r.name} <= #{literal(r.reset, r.type)};\n"

        tail =
          if body == [],
            do: ["    end\n"],
            else: ["    end else begin\n", body, "    end\n"]

        {["  always_ff @(#{sens}) begin\n", "    if (#{cond_}) begin\n", resets, tail, "  end\n"],
         st}
      end

    {b, st} =
      if plain == [] do
        {[], st}
      else
        names = MapSet.new(plain, & &1.name)

        case Stmt.slice(stmts, names) do
          [] ->
            {[], st}

          sl ->
            st = use_all(st, clk)
            {body, st} = stmts(sl, "<=", 2, st)
            {["  always_ff @(posedge #{clk}) begin\n", body, "  end\n"], st}
        end
      end

    {Enum.reject([a, b], &(&1 == [])), st}
  end

  # -- memories --------------------------------------------------------------------------

  defp memory_blocks(mem, st) do
    m = st.m

    {writes, st} =
      Enum.map_reduce(mem.write_ports, st, fn p, st ->
        clk = clock_of(m, p.domain)
        st = use_all(st, clk)
        {sa, st} = ex_top(p.addr, st)

        {body, st} =
          case p.be do
            nil ->
              {sd, st} = ex_top(p.data, st)
              {["#{mem.name}[#{sa}] <= #{sd};\n"], st}

            be ->
              n = div(mem.width, mem.byte)

              Enum.map_reduce(0..(n - 1), st, fn i, st ->
                {sb, st} = ex(Expr.bit(be, i), st)
                {sd, st} = ex(Expr.slice(p.data, i * mem.byte, mem.byte), st)
                hi = (i + 1) * mem.byte - 1
                lo = i * mem.byte
                {"if (#{sb}) #{mem.name}[#{sa}][#{hi}:#{lo}] <= #{sd};\n", st}
              end)
          end

        {lines, st} = guarded(p.en, body, 2, st)
        {["  always_ff @(posedge #{clk}) begin\n", lines, "  end\n"], st}
      end)

    {reads, st} =
      Enum.map_reduce(mem.read_ports, st, fn
        %{kind: :async}, st ->
          {[], st}

        p, st ->
          clk = clock_of(m, p.domain)
          st = st |> use_all(clk) |> use_all(mem.name)
          {sa, st} = ex_top(p.addr, st)
          {lines, st} = guarded(p.en, ["#{p.data} <= #{mem.name}[#{sa}];\n"], 2, st)
          {["  always_ff @(posedge #{clk}) begin\n", lines, "  end\n"], st}
      end)

    {Enum.reject(writes ++ reads, &(&1 == [])), st}
  end

  defp guarded(%Expr{op: :const, args: [1]}, lines, depth, st),
    do: {Enum.map(lines, &[ind(depth), &1]), st}

  defp guarded(en, lines, depth, st) do
    {se, st} = ex_top(en, st)

    {[
       "#{ind(depth)}if (#{se}) begin\n",
       Enum.map(lines, &[ind(depth + 1), &1]),
       "#{ind(depth)}end\n"
     ], st}
  end

  defp clock_of(m, dom), do: hd(Module.domain(m, dom).clock.args)

  # -- instances -------------------------------------------------------------------------

  defp instance(inst, st) do
    m = st.m

    {conns, st} =
      Enum.map_reduce(inst.conns, st, fn
        {port, {:wire, w}}, st ->
          # a child output drives the wire; only readers in this module use it
          st = if Module.port(inst.module, port).dir == :output, do: st, else: use_all(st, w)
          {{port, Atom.to_string(w)}, st}

        {port, {:clock, pd}}, st ->
          clk = clock_of(m, pd)
          {{port, Atom.to_string(clk)}, use_all(st, clk)}

        {port, {:reset, pd, invert}}, st ->
          rst = hd(Module.domain(m, pd).reset.args)
          {{port, if(invert, do: "!#{rst}", else: "#{rst}")}, use_all(st, rst)}
      end)

    {inouts, st} =
      Enum.map_reduce(Map.get(inst, :inouts, []), st, fn
        {port, nil}, st -> {{port, ""}, st}
        {port, n}, st -> {{port, Atom.to_string(n)}, use_all(st, n)}
      end)

    conns = conns ++ inouts
    pw = conns |> Enum.map(&String.length(Atom.to_string(elem(&1, 0)))) |> Enum.max(fn -> 0 end)
    last = length(conns) - 1

    lines =
      conns
      |> Enum.with_index()
      |> Enum.map(fn {{p, v}, i} ->
        "    .#{String.pad_trailing(Atom.to_string(p), pw)}(#{v})#{if i < last, do: ",", else: ""}\n"
      end)

    params =
      case inst.params do
        [] ->
          ""

        ps ->
          body = Enum.map_join(ps, ",\n", fn {k, v} -> "    .#{k}(#{param_value(v)})" end)
          " #(\n#{body}\n  )"
      end

    {["  #{inst.module.name}#{params} #{inst.name} (\n", lines, "  );\n"], st}
  end
end
