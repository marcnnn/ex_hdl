defmodule ExHdl.Backends.SystemVerilog.Stream do
  @moduledoc false
  # Shared pieces of the frame generators (polyphase filters, FFT, reorder
  # buffers): tdata field layout, the module header, the output buffer
  # that gives the pipeline its clock enable, and the
  # `ExHdl.Backends.SystemVerilog.Scan.Design` they return (so the stream
  # simulation and the synthesis helpers work unchanged).

  import Bitwise

  alias ExHdl.Backends.SystemVerilog.Scan.Design

  @doc "Fields `%{index:, type:, shape:, offset:, bits:}` for scalar leaves of `types`."
  def fields(types) do
    {fields, bits} =
      types
      |> Enum.with_index()
      |> Enum.map_reduce(0, fn {type, i}, off ->
        b = elem(type, 1)
        {%{index: i, type: type, shape: {}, offset: off, bits: b}, off + b}
      end)

    {fields, byte_align(bits)}
  end

  def byte_align(0), do: 8
  def byte_align(bits), do: div(bits + 7, 8) * 8

  @doc "Bits of the unsigned value `v` (at least 1)."
  def clog2(n) when n <= 1, do: 1
  def clog2(n), do: bit_len(n - 1)

  def bit_len(0), do: 0
  def bit_len(v), do: 1 + bit_len(v >>> 1)

  @doc "Bits of a signed value in `lo..hi`."
  def signed_bits(lo, hi) do
    Enum.max([bit_len(max(hi, 0)) + 1, bit_len(max(-lo - 1, 0)) + 1, 2])
  end

  @doc "A signed SystemVerilog literal of `bits` bits."
  def lit(v, bits) when v < 0, do: "-#{bits}'sd#{-v}"
  def lit(v, bits), do: "#{bits}'sd#{v}"

  @doc "The tdata field `f` of `bus` as a signed expression (one bit wider if unsigned)."
  def field(bus, %{type: {:s, b}, offset: o}), do: "$signed(#{bus}[#{o + b - 1}:#{o}])"
  def field(bus, %{type: {:u, b}, offset: o}), do: "$signed({1'b0, #{bus}[#{o + b - 1}:#{o}]})"

  @doc "Width of a field as a signed value."
  def field_bits(%{type: {:s, b}}), do: b
  def field_bits(%{type: {:u, b}}), do: b + 1

  @doc """
  Module header. `extra` are further port declarations (strings ending in
  ",\\n"); `frame: true` adds `s_axis_tlast` and `m_axis_tlast`.
  """
  def header(name, comment, in_width, out_width, opts \\ []) do
    frame = Keyword.get(opts, :frame, false)

    [
      "// Generated by ExHdl. Do not edit.\n",
      Enum.map(List.wrap(comment), &"// #{&1}\n"),
      "/* verilator lint_off UNUSEDSIGNAL */\n",
      "module #{name} (\n",
      "  input  logic clk,\n",
      "  input  logic rst_n,\n",
      Keyword.get(opts, :extra, []),
      "  input  logic [#{in_width - 1}:0] s_axis_tdata,\n",
      if(frame, do: "  input  logic s_axis_tlast,\n", else: []),
      "  input  logic s_axis_tvalid,\n",
      "  output logic s_axis_tready,\n",
      "  output logic [#{out_width - 1}:0] m_axis_tdata,\n",
      if(frame, do: "  output logic m_axis_tlast,\n", else: []),
      "  output logic m_axis_tvalid,\n",
      "  input  logic m_axis_tready\n",
      ");\n\n"
    ]
  end

  def footer, do: ["endmodule\n", "/* verilator lint_on UNUSEDSIGNAL */\n"]

  @doc """
  Output buffer of `depth` words: `push` (with `ce`) stores `data`
  (`width` bits, plus `m_axis_tlast` from `last` if given); declares `ce`,
  which is high while the buffer has room for one more item.
  """
  def out_buffer(data, width, push, opts \\ []) do
    depth = Keyword.get(opts, :depth, 4)
    last = Keyword.get(opts, :last)
    aw = clog2(depth)
    word = width + if(last, do: 1, else: 0)
    value = if last, do: "{#{last}, #{data}}", else: data
    ports = if last, do: "{m_axis_tlast, m_axis_tdata}", else: "m_axis_tdata"

    [
      "  // output buffer; the pipeline runs while it has room\n",
      "  logic [#{word - 1}:0] ob_mem [#{depth}];\n",
      "  logic [#{aw - 1}:0] ob_wp, ob_rp;\n",
      "  logic [#{aw}:0] ob_count;\n",
      "  logic ob_push, ob_pop;\n",
      "  assign ce = ob_count < #{aw + 1}'d#{depth};\n",
      "  assign ob_push = ce && (#{push});\n",
      "  assign ob_pop = m_axis_tvalid && m_axis_tready;\n",
      "  always_ff @(posedge clk) begin\n",
      "    if (!rst_n) begin\n",
      "      ob_wp <= '0;\n",
      "      ob_rp <= '0;\n",
      "      ob_count <= '0;\n",
      "    end else begin\n",
      "      if (ob_push) begin\n",
      "        ob_mem[ob_wp] <= #{value};\n",
      "        ob_wp <= ob_wp + #{aw}'d1;\n",
      "      end\n",
      "      if (ob_pop) ob_rp <= ob_rp + #{aw}'d1;\n",
      "      ob_count <= ob_count + #{aw + 1}'(ob_push) - #{aw + 1}'(ob_pop);\n",
      "    end\n",
      "  end\n",
      "  assign m_axis_tvalid = ob_count != '0;\n",
      "  assign #{ports} = ob_mem[ob_rp];\n"
    ]
  end

  @doc "A `Scan.Design` for a generated frame module."
  def design(name, source, inputs, outputs, in_width, out_width, opts) do
    %Design{
      name: name,
      source: IO.iodata_to_binary(source),
      latency: Keyword.fetch!(opts, :latency),
      ii: 1,
      channels: 1,
      state_stage: 0,
      write_stage: 0,
      inputs: inputs,
      outputs: outputs,
      busy: false,
      params: [],
      in_width: in_width,
      out_width: out_width,
      frame: Keyword.get(opts, :frame, false),
      dsp: Keyword.get(opts, :dsp, 0)
    }
  end
end
