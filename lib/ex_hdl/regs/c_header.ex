defmodule ExHdl.Regs.CHeader do
  @moduledoc """
  C header for an `ExHdl.Regs` map. Names are `<MAP>_<REG>_...` in upper
  case:

    * `<MAP>_<REG>_OFFSET` byte offset; arrays get `<MAP>_<REG>_OFFSET(i)`,
      `_COUNT` and `_STRIDE`; `<MAP>_<REG>_RESET` the reset value as read.
    * per field `_SHIFT`, `_WIDTH`, `_MASK` (in place), `_RESET`,
      `_GET(word)`, `_SET(word, value)` and one constant per enum value
      (`<MAP>_<REG>_<FIELD>_<NAME>`).
    * per window `<MAP>_<WIN>_OFFSET`, `_SIZE`, `_WORDS`.
  """

  import Bitwise

  alias ExHdl.Regs

  @doc "Header text."
  @spec render(Regs.t()) :: String.t()
  def render(%Regs{} = m) do
    p = String.upcase(m.name)
    guard = "#{p}_H"

    regs =
      Enum.map(m.registers, fn r ->
        rp = "#{p}_#{up(r.name)}"

        offset =
          case r.count do
            nil ->
              [define("#{rp}_OFFSET", hex(r.offset))]

            n ->
              [
                define(
                  "#{rp}_OFFSET(i)",
                  "(#{hex(r.offset)} + (uint32_t)(i) * #{hex(r.stride)})"
                ),
                define("#{rp}_COUNT", "#{n}u"),
                define("#{rp}_STRIDE", hex(r.stride))
              ]
          end

        fields =
          Enum.map(r.fields, fn f ->
            fp = "#{rp}_#{up(f.name)}"
            reset = if f.const != nil, do: f.const, else: f.reset

            [
              "/* #{f.name} [#{f.lo + f.width - 1}:#{f.lo}] #{f.access}#{doc(f.doc)} */\n",
              define("#{fp}_SHIFT", "#{f.lo}u"),
              define("#{fp}_WIDTH", "#{f.width}u"),
              define("#{fp}_MASK", hex(Regs.mask(f))),
              define("#{fp}_RESET", hex(reset)),
              define("#{fp}_GET(w)", "(((uint32_t)(w) & #{fp}_MASK) >> #{fp}_SHIFT)"),
              define(
                "#{fp}_SET(w, v)",
                "(((uint32_t)(w) & ~#{fp}_MASK) | (((uint32_t)(v) << #{fp}_SHIFT) & #{fp}_MASK))"
              ),
              Enum.map(f.enum, fn {n, v} -> define("#{fp}_#{up(n)}", "#{v}u") end)
            ]
          end)

        [
          "\n/* #{r.name}#{doc(r.doc)} */\n",
          offset,
          define("#{rp}_RESET", hex(Regs.reset_value(m, r.name))),
          fields
        ]
      end)

    wins =
      Enum.map(m.windows, fn w ->
        wp = "#{p}_#{up(w.name)}"

        [
          "\n/* window #{w.name} (#{w.access})#{doc(w.doc)} */\n",
          define("#{wp}_OFFSET", hex(w.offset)),
          define("#{wp}_SIZE", hex(w.size)),
          define("#{wp}_WORDS", "#{div(w.size, 4)}u")
        ]
      end)

    IO.iodata_to_binary([
      "/* Generated by ExHdl.Regs from register map #{m.name}. Do not edit. */\n",
      "#ifndef #{guard}\n#define #{guard}\n\n#include <stdint.h>\n\n",
      define("#{p}_ADDR_WIDTH", "#{m.addr_width}u"),
      regs,
      wins,
      "\n#endif /* #{guard} */\n"
    ])
  end

  defp up(a), do: a |> Atom.to_string() |> String.upcase()
  defp define(name, value), do: "#define #{name} #{value}\n"

  defp hex(v),
    do: "0x" <> String.pad_leading(Integer.to_string(v &&& 0xFFFF_FFFF, 16), 8, "0") <> "u"

  defp doc(nil), do: ""
  defp doc(d), do: ": " <> String.replace(d, "*/", "* /")
end
