defmodule ExHdl.RTL.SVTest do
  use ExUnit.Case, async: true
  use ExUnitProperties
  use ExHdl.RTL

  alias ExHdl.Backends.SystemVerilog.RTL, as: SV
  alias ExHdl.RTL.{CDC, Examples}
  alias ExHdl.Test.{RTLDesigns, RTLGen}

  test "header, nettype, ports and declarations" do
    m =
      module "decls" do
        a = input(:a, s(12))
        b = input(:b, 1)
        _unused = input(:spare, 4)
        y = output(:y, s(13))
        r = reg(:r, 3, reset: 5)
        t = reg(:t, 2, reset: nil, attrs: [shreg_extract: "no"])
        y <~ (a - 1)

        sync do
          r <~ add_wrap(r, b)
          t <~ r[0..1]
        end
      end

    src = SV.module_source(m)

    assert src =~
             ~r/\A\/\/ Generated by ExHdl \(ExHdl.RTL\) from module decls\. Do not edit\.\n`default_nettype none/

    assert src =~ "  input  logic signed [11:0] a,\n"
    assert src =~ "  /* verilator lint_off UNUSEDSIGNAL */\n  input  logic [3:0]         spare,\n"
    assert src =~ "assign y = 13'(a) - 13'sd1;"
    assert src =~ "r <= 3'd5;"
    assert src =~ "r <= r + 3'(b);"
    assert src =~ ~s|(* shreg_extract = "no" *) logic [1:0] t;|

    assert String.ends_with?(
             src,
             "endmodule\n\n/* verilator lint_on VARHIDDEN */\n/* verilator lint_on CMPCONST */\n/* verilator lint_on UNSIGNED */\n`default_nettype wire\n"
           )
  end

  test "casts keep SystemVerilog from widening intermediate results" do
    m =
      module "casts" do
        a = input(:a, 8)
        b = input(:b, 8)
        y = output(:y, 16)
        z = output(:z, 8)
        y <~ zext(sub_wrap(a, b), 16)
        z <~ ~~~a
      end

    src = SV.module_source(m)
    assert src =~ "assign y = 16'(8'(a - b));"
    assert src =~ "assign z = 8'(~a);"
  end

  test "instances, black-box parameters and sources" do
    files = SV.generate(RTLDesigns.delay_top(4))
    assert Map.keys(files) |> Enum.sort() == ["delay_line.sv", "delay_top_4.sv"]

    assert files["delay_top_4.sv"] =~
             "delay_line #(\n    .DEPTH(4)\n  ) u (\n    .clk(clk),\n    .d  (u_d),\n    .q  (u_q)\n  );"
  end

  test "hoisted subexpressions and list muxes" do
    m =
      module "hoist" do
        a = input(:a, 8)
        sel = input(:sel, 2)
        y = output(:y, 4)
        z = output(:z, 8)
        y <~ (a + 1)[1..4]
        z <~ mux(sel, [a, ~~~a, 7])
      end

    src = SV.module_source(m)
    assert src =~ "assign _t0 = 9'(a) + 9'd1;"
    refute src =~ "logic [7:0] _t1;\n  /* verilator lint_on"
    assert src =~ "assign y = _t0[4:1];"
    assert src =~ "default: _t1 = 8'd0;"
  end

  describe "Verilator lint" do
    @describetag :verilator

    defp lint!(mod) do
      dir = Path.join(System.tmp_dir!(), "ex_hdl_lint_#{System.unique_integer([:positive])}")
      File.mkdir_p!(dir)

      try do
        files =
          for {f, src} <- SV.generate(mod) do
            File.write!(Path.join(dir, f), src)
            Path.join(dir, f)
          end

        {out, status} =
          System.cmd("verilator", ["--lint-only", "-Wall", "--top-module", mod.name | files],
            stderr_to_stdout: true
          )

        assert status == 0, "#{mod.name}:\n#{out}"
      after
        File.rm_rf!(dir)
      end
    end

    test "examples, CDC cells and test designs lint clean with -Wall" do
      for m <- [
            Examples.counter(),
            Examples.crc32(),
            Examples.skid_buffer(),
            Examples.skid_buffer(
              Interface.axi_stream(data: 10, keep: false, user: 2, last: false)
            ),
            Examples.pulse_counter(),
            Examples.burst_fsm(),
            Examples.ram(),
            Examples.ram(style: :distributed, depth: 64, width: 16),
            CDC.sync_ff(),
            CDC.sync_ff(width: 4, stages: 3, reset: true),
            CDC.pulse_sync(),
            CDC.reset_sync(active: :high),
            CDC.handshake(32),
            RTLDesigns.async_fifo(),
            RTLDesigns.delay_top(),
            RTLDesigns.tdp_ram()
          ],
          do: lint!(m)
    end

    property "random expression modules lint clean" do
      check all(asts <- list_of(RTLGen.ast(), min_length: 1, max_length: 6), max_runs: 40) do
        m =
          module "lint_fuzz" do
            handles = Map.new(RTLGen.inputs(), fn {n, t} -> {n, input(n, t)} end)

            for {ast, i} <- Enum.with_index(asts) do
              e = RTLGen.build(ast, handles)
              o = output(:"o#{i}", e.type)
              o <~ e
            end
          end

        lint!(m)
      end
    end

    test "a child signal named like the parent's instance lints" do
      child =
        module "has_off" do
          a = input(:a, 8)
          y = output(:y, 8)
          off = wire(:off, a)
          y <~ off
        end

      lint!(
        module "inst_off" do
          a = input(:a, 8)
          q = output(:q, 8)
          u = instance(:off, child, connect: [a: a])
          q <~ u.y
        end
      )
    end

    test "widening a hoisted subexpression lints" do
      lint!(
        module "wide_hoist" do
          a = input(:a, 8)
          b = input(:b, 8)
          sel = input(:sel, 2)
          y = output(:y, 12)
          y <~ add_wrap(zext(mux(sel, [a, b, a &&& b, a ||| b]), 12), zext(a, 12))
        end
      )
    end

    test "an unread child output lints" do
      child =
        module "two_out" do
          a = input(:a, 8)
          y = output(:y, 8)
          z = output(:z, 8)
          y <~ a
          z <~ a
        end

      lint!(
        module "reads_one" do
          a = input(:a, 8)
          q = output(:q, 8)
          u = instance(:u, child, connect: [a: a])
          q <~ u.y
        end
      )
    end
  end

  test "SystemVerilog keywords are not signal names" do
    for kw <- [:within, :until, :ref, :table, :wire] do
      assert_raise ExHdl.RTL.ElaborationError, ~r/keyword/, fn ->
        module "kw" do
          a = input(:a, 1)
          wire(kw, a)
        end
      end
    end
  end

  @tag :yosys
  test "unary operators on casts parse in Yosys" do
    m =
      module "inv_wrap" do
        a = input(:a, 8)
        y = output(:y, 8)
        n = output(:n, s(9))
        y <~ ~~~sub_wrap(a, 1)
        n <~ -as_signed(sub_wrap(a, 1))
      end

    assert {:ok, _} = ExHdl.Synth.Yosys.utilization(SV.generate(m), "inv_wrap")
  end

  test "an indexed mux inside a cat generates" do
    m =
      module "cat_muxn" do
        sel = input(:sel, 2)
        y = output(:y, 8)
        r = for i <- 0..3, do: reg(:"r#{i}", 4)

        sync do
          for x <- r, do: x <~ add_wrap(x, 1)
        end

        y <~ cat([mux(sel, r), const(0, 4)])
      end

    assert SV.generate(m)["cat_muxn.sv"] =~ ~r/assign y = \{_t\d+, 4'(d|h|b)0\}/
  end
end
